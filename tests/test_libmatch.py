"""Masked library matcher: synthetic LIB386 trees and EXEs only (tests/libtree.py)."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from conftest import build_le_image, page_fill
from libtree import FAKE_CODE, fake_module, planted_fake_exe, write_lib
from reverseapoc import libmatch
from reverseapoc.le import LE
from reverseapoc.libmatch import (
    RUNTIME_CSV_COLUMNS,
    LibMatchReport,
    MatchRange,
    format_runtime_csv,
    load_libraries,
    read_runtime_csv,
    runtime_csv_path,
    scan_exe,
    write_runtime_csv,
)
from reverseapoc.targets import REPO_ROOT

FAKE_ROW = MatchRange(
    start=0x10200,
    end=0x10228,
    segment="_TEXT",
    module="fake",
    libraries=("DOS/CLIB3R.LIB",),
    versions=("10.6",),
    publics=("fake2_", "fake_"),
    status="unique",
)


def _scan(watcom, exe: bytes, versions=("10.6",), **kwargs) -> LibMatchReport:
    libraries, skipped = load_libraries(watcom, versions)
    return scan_exe(LE(exe), libraries, exe="SYNTH.EXE", skipped=skipped, **kwargs)


def _fake_report(tmp_path) -> LibMatchReport:
    watcom = tmp_path / "w"
    write_lib(watcom, "10.6", "DOS/CLIB3R.LIB", [fake_module()])
    return _scan(watcom, planted_fake_exe())


# ---- conftest page overlay ----


def test_build_le_image_patches_write_at_the_linear_address():
    img = build_le_image(patches={0x10200: b"\x01\x02", 0x11004: b"\x03", 0x20010: b"\x04"})
    flat = LE(img.data).load_flat()
    assert flat[0x10200:0x10202] == b"\x01\x02"
    assert flat[0x11004] == 0x03
    assert flat[0x20010] == 0x04
    assert flat[0x101FF] == page_fill(1)


def test_build_le_image_patches_follow_the_page_map():
    img = build_le_image(page_numbers=(2, 1, 3), patches={0x10010: b"\x05"})
    assert LE(img.data).load_flat()[0x10010] == 0x05


def test_build_le_image_patch_crossing_a_page_end_raises():
    with pytest.raises(AssertionError):
        build_le_image(patches={0x10FFF: b"\x01\x02"})


# ---- the planted module ----


def test_planted_module_is_found(tmp_path):
    report = _fake_report(tmp_path)
    assert list(report.ranges) == [FAKE_ROW]
    assert report.exe == "SYNTH.EXE"
    assert report.code_base == 0x10000
    assert report.code_size == 0x1800


def test_runtime_csv_round_trip(tmp_path):
    report = _fake_report(tmp_path)
    text = format_runtime_csv(report, "SYNTH.EXE")
    lines = text.splitlines()
    assert lines[0].startswith("# generated by")
    assert "SYNTH.EXE" in lines[0]
    assert lines[1] == ",".join(RUNTIME_CSV_COLUMNS)
    assert lines[1] == "start,end,segment,module,libraries,versions,publics,status,alternatives"
    assert lines[2] == "0x00010200,0x00010228,_TEXT,fake,DOS/CLIB3R.LIB,10.6,fake2_;fake_,unique,"
    assert text.endswith("\n") and "\r" not in text

    path = tmp_path / "sub" / "runtime.csv"
    write_runtime_csv(path, report, "SYNTH.EXE")
    assert path.read_text(encoding="utf-8") == text
    assert read_runtime_csv(path) == list(report.ranges)
    assert not list(path.parent.glob(".*.tmp"))


def test_runtime_csv_holds_addresses_and_names_only(tmp_path):
    report = _fake_report(tmp_path)
    text = format_runtime_csv(report, "SYNTH.EXE")
    rows = [line.split(",") for line in text.splitlines()[2:]]
    assert rows
    byte_run = re.compile(r"(?:[0-9A-Fa-f]{2}){4,}")
    for row in rows:
        assert re.fullmatch(r"0x[0-9A-F]{8}", row[0]) and re.fullmatch(r"0x[0-9A-F]{8}", row[1])
        assert not any(byte_run.search(cell) for cell in row[2:])
    for blob in (FAKE_CODE.hex(), FAKE_CODE[:8].hex()):
        assert blob not in text.lower()
    assert FAKE_CODE[:8].hex() not in str(report.to_json()).lower()


def test_report_format_has_one_line_per_range(tmp_path):
    report = _fake_report(tmp_path)
    lines = [line for line in report.format().splitlines() if line.startswith("0x")]
    assert lines == ["0x00010200-0x00010228  fake  DOS/CLIB3R.LIB  10.6  unique"]


def test_runtime_csv_path_is_in_the_exe_config_dir():
    assert runtime_csv_path("UFO2P.EXE") == REPO_ROOT / "config" / "ufo2p" / "runtime.csv"


def test_libmatch_carries_the_kknd_derivation_header():
    first = Path(libmatch.__file__).read_text(encoding="utf-8").splitlines()[0]
    assert first.startswith("# Derived from KKND-Decomp tools/lib_match.py (CC0 1.0)")

