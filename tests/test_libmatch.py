FAKE_ROW = MatchRange(
    start=0x10200,
    end=0x10228,
    segment="_TEXT",
    module="fake",
    libraries=("DOS/CLIB3R.LIB",),
    versions=("10.6",),
    publics=("fake2_", "fake_"),
    status="unique",
)


def _scan(watcom, exe: bytes, versions=("10.6",), **kwargs) -> LibMatchReport:
    libraries, skipped = load_libraries(watcom, versions)
    return scan_exe(LE(exe), libraries, exe="SYNTH.EXE", skipped=skipped, **kwargs)


def _fake_report(tmp_path) -> LibMatchReport:
    watcom = tmp_path / "w"
    write_lib(watcom, "10.6", "DOS/CLIB3R.LIB", [fake_module()])
    return _scan(watcom, planted_fake_exe())


