def test_build_le_image_patches_write_at_the_linear_address():
    img = build_le_image(patches={0x10200: b"\x01\x02", 0x11004: b"\x03", 0x20010: b"\x04"})
    flat = LE(img.data).load_flat()
    assert flat[0x10200:0x10202] == b"\x01\x02"
    assert flat[0x11004] == 0x03
    assert flat[0x20010] == 0x04
    assert flat[0x101FF] == page_fill(1)


def test_build_le_image_patches_follow_the_page_map():
    img = build_le_image(page_numbers=(2, 1, 3), patches={0x10010: b"\x05"})
    assert LE(img.data).load_flat()[0x10010] == 0x05


def test_build_le_image_patch_crossing_a_page_end_raises():
    with pytest.raises(AssertionError):
        build_le_image(patches={0x10FFF: b"\x01\x02"})


