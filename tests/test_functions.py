"""functions.csv and runtime seeding: synthetic rows and LIB386 trees only (tests/libtree.py).

Every address and name here is made up; the real runtime offsets are pinned in
tests/test_functions_lib_real.py.
"""

from __future__ import annotations

from pathlib import Path

import pytest

import omfimage as om
from libtree import body, code_module, write_lib
from reverseapoc.functions import (
    FUNCTIONS_CSV_COLUMNS,
    FUNCTIONS_CSV_COMMENT,
    FunctionRow,
    FunctionsError,
    format_functions_csv,
    functions_csv_path,
    read_functions_csv,
    runtime_entries,
    seed_runtime_rows,
    write_functions_csv,
)
from reverseapoc.libmatch import LoadedLibrary, MatchRange, load_libraries
from reverseapoc.targets import REPO_ROOT

LIB = "DOS/CLIB3R.LIB"
ROW_START = 0x10200


def _row(
    start: int,
    end: int,
    name: str,
    kind: str = "runtime",
    unit: str = "",
    evidence: str = "runtime",
) -> FunctionRow:
    return FunctionRow(start, end, name, kind, unit, evidence)


SAMPLE = [
    _row(0x10000, 0x10010, "func_00010000", "game", "first", "entry"),
    _row(0x10010, 0x10020, "zork_", "runtime", "", "runtime"),
    _row(0x10020, 0x10030, "func_00010020", "thunk", "first", "call"),
    _row(0x10040, 0x10044, "D_00010040", "data-in-code", "first", "capstone"),
]


def _libraries(tmp_path: Path, *modules: bytes, version: str = "10.6") -> list[LoadedLibrary]:
    watcom = tmp_path / "w"
    write_lib(watcom, version, LIB, list(modules))
    libraries, _ = load_libraries(watcom, (version,))
    return libraries


def _range(module: str, length: int, publics: tuple[str, ...], **kwargs) -> MatchRange:
    fields = {
        "start": ROW_START,
        "end": ROW_START + length,
        "segment": "_TEXT",
        "module": module,
        "libraries": (LIB,),
        "versions": ("10.6",),
        "publics": publics,
        "status": "unique",
    }
    fields.update(kwargs)
    return MatchRange(**fields)


# ---- functions.csv round trip ----


def test_functions_csv_round_trip(tmp_path):
    text = format_functions_csv(SAMPLE, name="UFO2P.EXE")
    lines = text.splitlines()
    assert lines[0] == "# generated by: uv run reverseapoc functions UFO2P.EXE --write; do not edit"
    assert lines[0] == FUNCTIONS_CSV_COMMENT.format(name="UFO2P.EXE")
    assert lines[1] == "start,end,name,kind,unit,evidence"
    assert tuple(lines[1].split(",")) == FUNCTIONS_CSV_COLUMNS
    assert lines[2] == "0x00010000,0x00010010,func_00010000,game,first,entry"
    path = tmp_path / "sub" / "functions.csv"
    write_functions_csv(path, SAMPLE, name="UFO2P.EXE")
    assert path.read_text(encoding="utf-8") == text
    assert read_functions_csv(path) == SAMPLE


def test_functions_csv_path_is_per_exe_config():
    assert functions_csv_path("UFO2P.EXE") == REPO_ROOT / "config" / "ufo2p" / "functions.csv"


def test_functions_csv_refuses_wrong_header(tmp_path):
    path = tmp_path / "functions.csv"
    path.write_text("start,end,name,kind,unit\n", encoding="utf-8")
    with pytest.raises(FunctionsError, match="header"):
        read_functions_csv(path)


def test_functions_csv_refuses_non_utf8(tmp_path):
    path = tmp_path / "functions.csv"
    path.write_bytes(b"start,end,name,kind,unit,evidence\n\xff\n")
    with pytest.raises(FunctionsError, match="UTF-8"):
        read_functions_csv(path)


# ---- runtime seeding ----


def test_seed_runtime_rows_splits_a_module_by_public_offsets(tmp_path):
    module = code_module("zork", body(8), publics=[("zork_", 0), ("zork2_", 1)])
    libraries = _libraries(tmp_path, module)
    rows = seed_runtime_rows([_range("zork", 8, ("zork2_", "zork_"))], libraries)
    assert rows == [
        _row(ROW_START, ROW_START + 1, "zork_"),
        _row(ROW_START + 1, ROW_START + 8, "zork2_"),
    ]


def test_seed_ignores_data_publics(tmp_path):
    code, data = body(8), body(4, seed=0x61)
    module = om.module(
        "mixed",
        om.lnames("", "_TEXT", "CODE", "_DATA", "DATA"),
        om.segdef32(2, 3, len(code)),
        om.segdef32(4, 5, len(data)),
        om.pubdef32(1, [("mixed_", 0)]),
        om.pubdef32(2, [("mixed_table", 2)]),
        om.ledata32(1, 0, code),
        om.ledata32(2, 0, data),
    )
    libraries = _libraries(tmp_path, module)
    rows = seed_runtime_rows([_range("mixed", 8, ("mixed_", "mixed_table"))], libraries)
    assert rows == [_row(ROW_START, ROW_START + 8, "mixed_")]


def test_seed_aliases_at_one_offset_give_one_row(tmp_path):
    # Orchestrator ruling F12: one row per distinct offset, named by the alias without a leading
    # underscore (else the first in sorted order); never a zero-length row.
    publics = [("_quux_", 0), ("quux_", 0), ("_nquux_", 4), ("_aquux_", 4)]
    libraries = _libraries(tmp_path, code_module("quux", body(8), publics=publics))
    runtime = [_range("quux", 8, ("_aquux_", "_nquux_", "_quux_", "quux_"))]
    rows = seed_runtime_rows(runtime, libraries)
    assert rows == [
        _row(ROW_START, ROW_START + 4, "quux_"),
        _row(ROW_START + 4, ROW_START + 8, "_aquux_"),
    ]
    entries = runtime_entries(runtime, libraries)
    assert [e.aliases for e in entries] == [("_quux_", "quux_"), ("_aquux_", "_nquux_")]


def test_seed_leaves_bytes_before_the_first_public_uncovered(tmp_path):
    libraries = _libraries(tmp_path, code_module("gap", body(8), publics=[("gap_", 3)]))
    rows = seed_runtime_rows([_range("gap", 8, ("gap_",))], libraries)
    assert rows == [_row(ROW_START + 3, ROW_START + 8, "gap_")]


def test_seed_ignores_a_public_at_the_segment_end(tmp_path):
    # An end label (like ___GETDSEnd_) starts no function; it never becomes a zero-length row.
    module = code_module("lbl", body(8), publics=[("lbl_", 0), ("lblEnd_", 8)])
    libraries = _libraries(tmp_path, module)
    rows = seed_runtime_rows([_range("lbl", 8, ("lblEnd_", "lbl_"))], libraries)
    assert rows == [_row(ROW_START, ROW_START + 8, "lbl_")]


def test_seed_finds_a_module_named_by_another_version(tmp_path):
    # runtime.csv names a range after the first module name of every version that matched it; the
    # 10.6 module may only be listed among the alternatives.
    libraries = _libraries(tmp_path, code_module("cmpx", body(8), publics=[("cmpx_", 0)]))
    runtime = [_range("_cmpx", 8, ("cmpx_",), status="ambiguous", alternatives=(f"cmpx@{LIB}",))]
    assert seed_runtime_rows(runtime, libraries) == [_row(ROW_START, ROW_START + 8, "cmpx_")]


def test_seed_uses_the_rows_first_version_when_it_lacks_the_preferred_one(tmp_path):
    module = code_module("old", body(8), publics=[("old_", 2)])
    libraries = _libraries(tmp_path, module, version="10.5")
    runtime = [_range("old", 8, ("old_",), versions=("10.5",))]
    assert seed_runtime_rows(runtime, libraries) == [_row(ROW_START + 2, ROW_START + 8, "old_")]


def test_seed_refuses_a_row_whose_module_is_missing(tmp_path):
    libraries = _libraries(tmp_path, code_module("zork", body(8)))
    with pytest.raises(FunctionsError, match="nothere"):
        seed_runtime_rows([_range("nothere", 8, ("nothere_",))], libraries)


def test_seed_refuses_a_module_whose_segment_length_differs(tmp_path):
    libraries = _libraries(tmp_path, code_module("zork", body(8)))
    with pytest.raises(FunctionsError, match="zork"):
        seed_runtime_rows([_range("zork", 9, ("zork_",))], libraries)
