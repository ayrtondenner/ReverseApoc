class ConfigureError(ValueError):
    """build.ninja cannot safely carry the named path."""


# ninja 1.11 (the container's) has no escape for these in a build path.
_UNESCAPABLE = ("|", "\n", "\r")

# The orig dir is written unquoted into the check-orig and rebuild commands, which /bin/sh runs
# in the container and CreateProcess splits on Windows; no quoting is portable across both, so
# only characters that need none are accepted. `:` covers a drive letter (see _relative).
_SAFE_ORIG = re.compile(r"[A-Za-z0-9._/:-]+")

# EXE config dirs and unit names go into build paths, commands and Watcom file names unescaped.
_UNIT_NAME = re.compile(r"[a-z0-9_]+")

# D-12 detection by regex over the unit file (research Pattern 4; `check` later confirms the
# definitions from the compiled publics). Comments (block and //, which wcc386 and clang gnu89
# both accept) and string or character literals are blanked first, keeping line breaks so
# directive line numbers stay true; an unterminated block comment runs to the end of the file,
# as it would for the compiler. The text is normalised first (normalize_source: trigraphs, line
# breaks, blanks after a splicing backslash; re-review N1). Then a backslash-newline splices
# lines before comments and literals are recognised (translation phase 2 before phase 3;
# DI-05, 06-03 review I1/M1), so a splice
# may sit inside a comment delimiter (`/\<nl>*`, `*\<nl>/`, `/\<nl>/`) or between an escape's
# backslash and its character, and a `//` comment runs on through one. _blank turns every line
# break inside a comment or literal into a splice, so the logical line it sits in (a directive
# included) runs on, as it does for the compiler, which sees a comment as one space.
_SPLICES = r"(?:\\\n)*"


def _literal(quote: str) -> str:
    """A string or character literal: escapes (splices allowed after the backslash, and a
    splice is itself `\\` + newline) or any character but the quote, a backslash or a newline."""
    return rf"{quote}(?:\\{_SPLICES}.|[^{quote}\\\n])*{quote}"


_COMMENT_OR_LITERAL = re.compile(
    rf"/{_SPLICES}\*.*?(?:\*{_SPLICES}/|\Z)|/{_SPLICES}/(?:\\\n|[^\n])*"
    rf"|{_literal(chr(34))}|{_literal(chr(39))}",
    re.DOTALL,
)

# Translation phases 1-2 as wcc386 10.6 does them (06-03 re-review N1, observed with
# `wcc386 -zq -p`): C89 trigraphs map first, everywhere, literals included; a CRLF is one line
# break; and a backslash followed by spaces or tabs and then a newline is a splice, as a
# backslash-newline is. A form feed or vertical tab after the backslash is not. No rewrite adds
# or removes a line break. A lone CR (not followed by LF) is refused (re-review R2-1): wcc386
# ends a // comment there but keeps it inside a literal as a character, so no one mapping of it
# reads as the compiler does, and read_text, which turns it into a line break, hid live code.
_TRIGRAPHS = {"=": "#", "/": "\\", "'": "^", "(": "[", ")": "]", "!": "|", "<": "{", ">": "}",
              "-": "~"}  # fmt: skip
_TRIGRAPH = re.compile(r"\?\?([=/'()!<>-])")
_CRLF = "\r\n"
_LONE_CR = re.compile(r"\r(?!\n)")
_LONE_CR_BYTES = re.compile(rb"\r(?!\n)")
_BLANK_SPLICE = re.compile(r"\\[ \t]+\n")


def lone_cr_problem(line: int) -> str:
    """The refusal of a lone carriage return on `line` (1-based)."""
    return (
        f"line {line}: a carriage return not followed by a line feed, which wcc386 reads as a "
        "line break in a // comment but as a character in a literal, so the check cannot read "
        "it; save the file with LF or CRLF line ends"
    )


def normalize_source(text: str) -> str:
    """`text` after translation phases 1-2 up to the splice itself: trigraphs mapped, CRLF made
    LF, and blanks between a splicing backslash and its newline removed; the line count is
    kept. Raises _UnreadableSource for a lone CR, naming its line."""
    lone = _LONE_CR.search(text)
    if lone is not None:
        raise _UnreadableSource(lone_cr_problem(text.count("\n", 0, lone.start()) + 1))
    text = _TRIGRAPH.sub(lambda match: _TRIGRAPHS[match.group(1)], text)
    return _BLANK_SPLICE.sub(_SPLICE + "\n", text.replace(_CRLF, "\n"))


class _SourceScanner:
    """The comment-and-literal scanner, run on normalize_source's output. check.source_marks
    calls `_NOT_CODE.sub(_blank, text)` on the raw unit file, so the normalisation lives in
    `sub` and every caller gets it; new callers use code_text."""

    def __init__(self, pattern: re.Pattern[str]) -> None:
        self.pattern = pattern

    def sub(self, repl: Callable[[re.Match[str]], str], text: str) -> str:
        return self.pattern.sub(repl, normalize_source(text))


_NOT_CODE = _SourceScanner(_COMMENT_OR_LITERAL)
# Preprocessor conditionals: only `#if 0` is understood (its block is dead, nested conditionals
# included, and its #else branch is live); any other conditional is refused, never guessed.
_DIRECTIVE = re.compile(r"[ \t]*#[ \t]*([A-Za-z_]+)(.*)")
_SPLICE = "\\"  # a physical line ending in a backslash continues on the next one
_OPENERS = ("if", "ifdef", "ifndef")
_IF_ZERO = "0"
_PLACEHOLDER = r"func_[0-9A-F]{8}"
_MARKER = re.compile(rf"\bINCLUDE_ASM\s*\(\s*({_PLACEHOLDER})\s*\)\s*;")
# A declarator whose parameter list (one level of nested parentheses, for function pointers) is
# followed by `{`: a definition. A prototype ends in `;` and a call never meets a `{` directly.
_DEFINITION = re.compile(rf"\b({_PLACEHOLDER})\s*\((?:[^()]|\([^()]*\))*\)\s*\{{")
_CHECKED_KINDS = (KIND_GAME, KIND_THUNK)  # orchestrator ruling F5: runtime, data-in-code exempt


def ninja_path(path: str) -> str:
    """Escape a path for use in a ninja build line."""
    bad = next((c for c in _UNESCAPABLE if c in path), None)
    if bad is not None:
        raise ConfigureError(
            f"{path!r} holds {bad!r}, which ninja 1.11 (the container's) cannot escape in a "
            "build path; rename the file"
        )
    try:
        path.encode("utf-8")
    except UnicodeEncodeError:
        raise ConfigureError(
            f"{path!r} is not valid UTF-8, and build.ninja is written as UTF-8; rename the file"
        ) from None
    return path.replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def _refuse_option_like(path: str) -> str:
    """`path`, unless reverseapoc's argparse would read it as an option."""
    if path.startswith("-"):
        raise ConfigureError(
            f"{path!r} starts with '-', so the reverseapoc command in build.ninja would read it "
            "as an option; rename or move the file or directory"
        )
    return path


def _check_command_path(path: str, what: str, commands: str) -> str:
    if not _SAFE_ORIG.fullmatch(path):
        raise ConfigureError(
            f"{what} {path!r} is written unquoted into the {commands} commands, which /bin/sh "
            "runs in the container and CreateProcess splits on Windows, so only ASCII letters, "
            "digits and . _ - / : are accepted; rename or move it"
        )
    return _refuse_option_like(path)


def _check_orig_dir(orig: str) -> str:
    return _check_command_path(orig, "orig path", "check-orig, verify, target, asm and land")


def _check_name(what: str, name: str) -> str:
    if not _UNIT_NAME.fullmatch(name):
        raise ConfigureError(
            f"{what} {name!r} is not [a-z0-9_]+, so build.ninja cannot carry it unescaped"
        )
    return name


def _blank(match: re.Match[str]) -> str:
    """A comment becomes spaces and a literal an empty one. Every line break inside either
    becomes a splice (backslash-newline): the line count stays true for directive numbers, and
    the logical line the comment or literal sits in runs on, as it does for the compiler (a
    comment is one space; a literal holds only spliced line breaks)."""
    found = match.group()
    breaks = found.count("\n")
    if found.startswith("/"):
        return re.sub(r"[^\n]", " ", found).replace("\n", _SPLICE + "\n")
    return found[0] + (_SPLICE + "\n") * breaks + found[-1]


class _ConditionalError(ValueError):
    """A preprocessor conditional the D-12 check cannot evaluate (it fails closed)."""


class _UnreadableSource(_ConditionalError):
    """Text the D-12 check cannot read as wcc386 does, such as a lone CR (it fails closed). A
    _ConditionalError, so every caller that refuses a conditional (check.source_marks
    included) refuses it the same way."""


def _refuse_conditional(number: int, name: str, why: str) -> _ConditionalError:
    return _ConditionalError(f"line {number}: #{name} {why}; a unit file may use only #if 0")


def _directive_step(
    number: int, name: str, rest: str, dead: int, live_else: int
) -> tuple[int, int]:
    """The next (dead, live_else) state after one directive. `dead` is the nesting depth inside
    the dead branch of an #if 0 (0 when live); `live_else` counts the live #else branches of
    #if 0 blocks still waiting for their #endif."""
    if dead:
        if name in _OPENERS:
            return dead + 1, live_else
        if name == "endif":
            return dead - 1, live_else
        if dead == 1 and name == "else":
            return 0, live_else + 1
        if dead == 1 and name == "elif":
            raise _refuse_conditional(number, name, "is a conditional the check cannot evaluate")
        return dead, live_else
    if name == "if" and rest == _IF_ZERO:
        return 1, live_else
    if name in (*_OPENERS, "elif"):
        raise _refuse_conditional(number, name, "is a conditional the check cannot evaluate")
    if name == "else":
        raise _refuse_conditional(number, name, "is outside the dead branch of an #if 0")
    if name == "endif":
        if not live_else:
            raise _refuse_conditional(number, name, "has no matching #if 0")
        return 0, live_else - 1
    return dead, live_else


def _live_code(code: str) -> str:
    """`code` (comments already blanked) with every directive line and every line of a dead
    #if 0 branch blanked, line breaks kept. Raises _ConditionalError for any conditional other
    than #if 0, an unmatched #else or #endif, or an #if 0 left open at the end of the file."""
    lines = code.split("\n")
    dead = live_else = 0
    opened = 0  # the line of the outermost #if 0 or its #else still open
    for first, last, logical in _logical_lines(lines):
        match = _DIRECTIVE.fullmatch(logical)
        if match is not None:  # a directive is reported at the physical line of its `#`
            number = _physical_line(lines, first, logical.index("#")) + 1
        if match is None:
            # Code is read spliced, as the compiler reads it: the logical line on its first
            # physical line, the lines it absorbed left empty so later numbers stay true.
            rest = [""] * (last - first)
            lines[first : last + 1] = [""] * (last + 1 - first) if dead else [logical, *rest]
            continue
        # A directive's text (a macro body and its continuation lines included) is not code.
        lines[first : last + 1] = [""] * (last + 1 - first)
        was_open = dead or live_else
        dead, live_else = _directive_step(
            number, match.group(1), match.group(2).strip(), dead, live_else
        )
        if not was_open:
            opened = number
    if dead or live_else:
        raise _ConditionalError(f"line {opened}: #if 0 has no matching #endif")
    return "\n".join(lines)


def _physical_line(lines: Sequence[str], first: int, position: int) -> int:
    """The 0-based physical line holding character `position` of the logical line that starts
    at `lines[first]` (each physical line counted without its splicing backslash)."""
    index = first
    while (index + 1 < len(lines) and lines[index].endswith(_SPLICE)
           and position >= len(lines[index]) - len(_SPLICE)):  # fmt: skip
        position -= len(lines[index]) - len(_SPLICE)
        index += 1
    return index


def _logical_lines(lines: Sequence[str]) -> Iterator[tuple[int, int, str]]:
    """(first, last, text) per logical line: physical lines `first`..`last` (0-based) joined
    where one ends in a backslash, the backslash-newline removed (translation phase 2)."""
    first = 0
    while first < len(lines):
        last = first
        while lines[last].endswith(_SPLICE) and last + 1 < len(lines):
            last += 1
        parts = [line.removesuffix(_SPLICE) for line in lines[first:last]]
        yield first, last, "".join([*parts, lines[last]])
        first = last + 1


def code_text(text: str) -> str:
    """The live code of a unit file as the D-12 check reads it: translation phases 1-2
    (normalize_source), comments and literals blanked, directives and dead #if 0 branches
    removed, line count kept. The one entry point the D-12 check, check.source_marks (through
    the same objects) and 06-12's hooks share. Raises _ConditionalError like _live_code."""
    return _live_code(_NOT_CODE.sub(_blank, text))


# 06-REVIEW CR-02: an #include names a bare header name (`"name.h"` from src/<exe>/ or include/,
# `<name.h>` from include/ or the compiler's own headers), never a path, another extension or a
# macro, so no file outside those (an attempt's notes.md under build/driver/, say) can carry a
# #pragma or inline asm into the compile past the scan.
_INCLUDE_DIRECTIVE = re.compile(r"\s*(?:#|%:)\s*include(.*)", re.DOTALL)
_BARE_HEADER = re.compile(r'\s*(?:"[A-Za-z0-9_]+\.h"|<[A-Za-z0-9_]+\.h>)\s*')


def _blank_comment(match: re.Match[str]) -> str:
    """A comment blanked as _blank does it; a literal kept as it is (the `"name.h"` of an
    #include is a header name, which _blank would empty)."""
    found = match.group()
    return _blank(match) if found.startswith("/") else found


def include_problems(text: str) -> list[str]:
    """CR-02: one problem per #include whose operand is not a bare header name, read through
    translation phases 1-2 with comments blanked, at its logical line's first line. "name.h"
    resolves in the including file's directory (src/<exe>/, which the agent cannot write) first,
    then as <name.h> does: in include/, then Watcom's own H directory (-i=include/;<watcom>/H),
    which game code may need (conio.h, i86.h), so angle includes are not restricted further. An
    #include in a dead #if 0 branch is refused too (fail closed). Raises _UnreadableSource for
    text normalize_source refuses."""
    problems = []
    for first, _last, logical in _logical_lines(_NOT_CODE.sub(_blank_comment, text).split("\n")):
        match = _INCLUDE_DIRECTIVE.match(logical)
        if match is None or _BARE_HEADER.fullmatch(match.group(1)):
            continue
        problems.append(
            f"line {first + 1}: an #include of {match.group(1).strip()!r}; an #include names only "
            'a bare header name: "name.h" from include/, or <name.h> from include/ or the '
            "compiler's own headers"
        )
    return problems


def check_unit_source(
    text: str,
    unit_functions: Sequence[FunctionRow],
    *,
    names: Mapping[str, int] | None = None,
    all_names: Mapping[str, int] | None = None,
) -> list[str]:
    """The D-12 problems of one unit file, read by the shared finder (unitdefs.find, D-29):
    every game or thunk row of the unit is defined in C under its current C name or marked
    INCLUDE_ASM (under its C name or its old placeholder), exactly once and not both, and no
    marker or definition names a function outside the unit; a definition under the old
    placeholder of a renamed row is refused. Problems name each row by its C name. `names` and
    `all_names` map C names to starts as for unitdefs.find (the unit loop passes the EXE's
    unitdefs.c_names as `all_names`; with neither, the rows' placeholders). The order of the file
    does not
    matter. Comments and dead #if 0 branches do not count; any other preprocessor conditional is
    itself a problem (the check fails closed rather than guess). A K&R-style definition is not
    recognised, so it is reported as neither defined nor marked (a false refusal, never a false
    pass). Any #include of something other than a bare header name is a problem too (CR-02)."""
    try:
        includes = include_problems(text)
    except _ConditionalError as exc:
        return [str(exc)]
    found = unitdefs.find(text, unit_functions, placeholders=unitdefs.placeholders(unit_functions),
                          names=names, all_names=all_names)  # fmt: skip
    return [*includes, *found.problems]


@dataclass(frozen=True)
class UnitBuild:
    """One units.csv row of one EXE, as build.ninja, objdiff.json and clangd see it. Paths are
    relative to the build.ninja directory, like the exe paths render() takes."""

    exe: str  # the config dir stem, e.g. ufo2p
    exe_name: str  # the manifest name, e.g. UFO2P.EXE
    unit: str
    source: str | None  # src/<exe>/<unit>.c, when the unit has C
    functions: tuple[FunctionRow, ...] = ()  # the functions.csv rows of the unit
    inputs: tuple[str, ...] = ()  # the config files the target cut reads

    def output(self, kind: str, suffix: str = ".o") -> str:
        """`<exe>/<kind>/<unit><suffix>` under the builddir, without the builddir."""
        return f"{self.exe}/{kind}/{self.unit}{suffix}"


@dataclass(frozen=True)
class Layout:
    """Repository files build.ninja names, relative to the build.ninja directory. The defaults
    are a build.ninja at the repository root."""

    configure: str = "configure.py"
    config: str = "config"  # --config, passed back by the regeneration command
    src: str = "src"  # --src, likewise
    output: str = "build.ninja"  # the build.ninja file name
    cc_inputs: tuple[str, ...] = ()  # cflags, the Watcom manifest and the project headers
    src_dirs: tuple[str, ...] = ()  # existing src/<exe> dirs: a new unit file re-runs configure
    # include/, when it exists: a header added or removed changes every cc edge's inputs, so it
    # re-runs configure too (06-09 fix round 2, N1).
    header_dirs: tuple[str, ...] = ()
    # The config dir the rules that read config/ are told about (DI-06c), or None for the
    # repository's own tree, which every reverseapoc verb reads by default.
    rule_config: str | None = None

    @classmethod
    def for_base(
        cls, base: Path, *, config: Path, src: Path, output: Path, exes: Sequence[str] = ()
    ) -> Layout:
        """The layout of a build.ninja in `base`; `exes` are the config dir stems with units."""
        # The project headers the provenance stamp covers too: one definition (compiler.py).
        headers = project_headers(ROOT)
        cc_inputs = [ROOT / name for name in CC_CONFIG] + headers
        src_dirs = [src / exe for exe in exes if (src / exe).is_dir()]
        header_dirs = [ROOT / INCLUDE_DIR] if (ROOT / INCLUDE_DIR).is_dir() else []
        default_config = config.resolve() == (ROOT / DEFAULT_CONFIG).resolve()
        return cls(
            configure=_relative(ROOT / "configure.py", base),
            config=_relative(config, base),
            src=_relative(src, base),
            output=output.name,
            cc_inputs=tuple(_relative(p, base) for p in cc_inputs),
            src_dirs=tuple(_relative(p, base) for p in src_dirs),
            header_dirs=tuple(_relative(p, base) for p in header_dirs),
            rule_config=None if default_config else _relative(config, base),
        )


def _config_arguments(layout: Layout) -> dict[str, str]:
    """The HEADER arguments that point the config-reading rules at `layout.rule_config`: the
    manifest for check-orig and rebuild, the manifest and config dir for target and land, and
    the manifest and per-EXE CSVs for asm (its `$exe` is the config dir stem). All empty for
    the repository's own config tree, so the default text is unchanged."""
    if layout.rule_config is None:
        return {"manifest_config": "", "unit_config": "", "asm_config": ""}
    rules = "target, land, asm, check-orig and rebuild"
    config = ninja_path(_check_command_path(layout.rule_config, "config dir", rules))
    manifest = f" --manifest {config}/{MANIFEST_NAME}"
    return {
        "manifest_config": manifest,
        "unit_config": f"{manifest} --config {config}",
        "asm_config": f"{manifest} --functions {config}/$exe/{FUNCTIONS_NAME} "
        f"--symbols {config}/$exe/{SYMBOLS_NAME}",
    }


def _built(path: str) -> str:
    return f"$builddir/{path}"


def _implicit(paths: Sequence[str], *, built: bool = False) -> str:
    """` | <paths>`: repository paths are escaped, `$builddir/...` outputs (built) are not."""
    if not paths:
        return ""
    return f" | {' '.join(paths if built else (ninja_path(p) for p in paths))}"


def _phony(name: str, outputs: Sequence[str]) -> str:
    return " ".join([f"build {name}: phony", *outputs])


def _base_objects(units: Sequence[UnitBuild]) -> list[str]:
    return [_built(u.output("base")) for u in units if u.source is not None]


def _lint_edges(units: Sequence[UnitBuild], layout: Layout) -> list[str]:
    """One stamp per unit file, rewritten only when the lint gate passes."""
    lines, stamps = [], []
    for unit in units:
        if unit.source is None:
            continue
        stamp = _built(unit.output("lint", ".stamp"))
        headers = [p for p in layout.cc_inputs if p.endswith(".h")]
        lines.append(f"build {stamp}: lint {ninja_path(unit.source)}{_implicit(headers)}")
        stamps.append(stamp)
    return [*lines, _phony("lint", stamps)]


def _asm_edges(units: Sequence[UnitBuild]) -> list[str]:
    """One always-run listing edge per EXE with units."""
    lines, outputs = [], []
    for exe in dict.fromkeys(unit.exe for unit in units):
        out = f"$builddir/always/asm/{exe}"
        lines += [f"build {out}: asm", f"  exe = {exe}"]
        outputs.append(out)
    return [*lines, _phony("asm", outputs)]


def _regeneration_edge(units: Sequence[UnitBuild], layout: Layout) -> list[str]:
    deps = [layout.configure, *dict.fromkeys(p for unit in units for p in unit.inputs)]
    deps += [unit.source for unit in units if unit.source is not None]
    deps += layout.src_dirs
    deps += layout.header_dirs
    return [f"build {ninja_path(layout.output)}: configure{_implicit(deps)}"]


def _unit_edges(unit: UnitBuild, orig: str, layout: Layout) -> list[str]:
    _check_name("EXE config dir", unit.exe)
    _check_name("unit", unit.unit)
    target_deps = [f"{orig}/{unit.exe_name}", *unit.inputs]
    lines = [
        f"build {_built(unit.output('target'))}: target{_implicit(target_deps)}",
        f"  exe = {unit.exe}",
        f"  unit = {unit.unit}",
    ]
    if unit.source is None:
        return lines
    src = ninja_path(_refuse_option_like(unit.source))
    obj = _built(unit.output("obj", ".obj"))
    # The provenance stamp `reverseapoc cc` writes next to the object (DI-06 part a) is an
    # implicit output: ninja rebuilds an object that has none, and the land step refuses one
    # whose stamp is missing or stale. Like the object, it is a checked-name builddir path.
    stamp = _built(unit.output("obj", ".obj" + PROV_SUFFIX))
    lines += [
        f"build {obj}{_implicit([stamp], built=True)}: cc {src}{_implicit(layout.cc_inputs)}",
        f"build {_built(unit.output('base'))}: omf2elf {obj}",
    ]
    return lines


def render(
    exes: list[str],
    *,
    orig: str = "orig",
    units: Sequence[UnitBuild] = (),
    layout: Layout | None = None,
) -> str:
    """build.ninja text for executables given as paths relative to the build.ninja directory.
    `orig` is the orig directory relative to the build.ninja directory, like the exe paths.
    The rebuild rule writes into `build` next to build.ninja, the builddir. `units` adds the
    compile, convert and cut edges of every unit; `layout` names the files they depend on.

    Raises ConfigureError for a path build.ninja cannot safely carry."""
    orig = _check_orig_dir(orig)
    layout = layout or Layout()
    regeneration = "regeneration"
    header = HEADER.format(
        orig=orig,
        configure=_check_command_path(layout.configure, "configure.py path", regeneration),
        config=_check_command_path(layout.config, "config dir", regeneration),
        src=_check_command_path(layout.src, "src dir", regeneration),
        **_config_arguments(layout),
    )
    lines = [
        header,
        "build $builddir/always/check-orig: check_orig",
        "build check-orig: phony $builddir/always/check-orig",
        "build $builddir/always/verify: rebuild",
        # Zero-regression gate: every unit's C is compiled and converted before land splices
        # the matched functions and checks the SHA-1.
        f"build $builddir/always/land: land{_implicit(_base_objects(units), built=True)}",
        "build verify: phony $builddir/always/verify $builddir/always/land",
        "",
    ]
    outputs = []
    for exe in exes:
        src = ninja_path(_refuse_option_like(exe))  # first, so a refusal names the whole path
        out = f"$builddir/always/parse-le/{ninja_path(Path(exe).name)}"
        lines.append(f"build {out}: parse_le {src}")
        outputs.append(out)
    lines.append(" ".join(["build parse-le: phony", *outputs]))
    lines.append("")
    for unit in units:
        lines += _unit_edges(unit, orig, layout)
    objects = [obj for unit in units for obj in _unit_objects(unit)]
    lines += [_phony("objects", objects), ""]
    lines += [*_lint_edges(units, layout), "", *_asm_edges(units), ""]
    lines += _regeneration_edge(units, layout)
    lines += ["", "default check-orig objects", ""]
    return "\n".join(lines)


def _unit_objects(unit: UnitBuild) -> list[str]:
    objects = [_built(unit.output("target"))]
    if unit.source is not None:
        objects.insert(0, _built(unit.output("base")))
    return objects


def _objdiff_unit(unit: UnitBuild) -> dict:
    entry: dict = {
        "name": f"{unit.exe}/{unit.unit}",
        "target_path": f"{BUILDDIR}/{unit.output('target')}",
    }
    metadata: dict = {"progress_categories": [unit.exe]}
    if unit.source is not None:
        entry["base_path"] = f"{BUILDDIR}/{unit.output('base')}"
        metadata = {"source_path": unit.source, **metadata}
    entry["metadata"] = metadata
    return entry


def render_objdiff(units: Sequence[UnitBuild]) -> str:
    """objdiff.json (objdiff 3.8.2 schema) for `units`; paths relative to its directory, which
    is the build.ninja directory. A unit without C has no base object yet."""
    exes = dict.fromkeys((unit.exe, unit.exe_name) for unit in units)
    config = {
        "$schema": OBJDIFF_SCHEMA,
        "min_version": OBJDIFF_MIN_VERSION,
        "custom_make": "ninja",
        "build_target": False,
        "build_base": True,
        "watch_patterns": list(OBJDIFF_WATCH),
        "progress_categories": [{"id": exe, "name": name} for exe, name in exes],
        "units": [_objdiff_unit(unit) for unit in units],
    }
    return json.dumps(config, indent=2) + "\n"


def render_compile_commands(units: Sequence[UnitBuild], base: Path) -> str:
    """compile_commands.json for clangd: one entry per unit with C, in the lint gate's dialect.
    The lint flags name include/ relative to the repository root, so that is the directory."""
    entries = []
    for unit in units:
        if unit.source is None:
            continue
        file = (base / unit.source).resolve().as_posix()
        entries.append(
            {"directory": ROOT.as_posix(), "file": file,
             "arguments": [CLANG, *CLANGD_FLAGS, "-c", file]}  # fmt: skip
        )
    return json.dumps(entries, indent=2) + "\n"


def find_executables(orig_dir: Path) -> list[Path]:
    """*.exe files directly in `orig_dir` (any case), sorted by name ignoring case."""
    if not orig_dir.is_dir():
        return []
    exes = [p for p in orig_dir.iterdir() if p.is_file() and p.suffix.lower() == ".exe"]
    return sorted(exes, key=lambda p: p.name.casefold())


def _exe_units(name: str, config: Path, src: Path, base: Path) -> Iterator[UnitBuild]:
    exe = PurePosixPath(name).stem.lower()
    exe_config = config / exe
    units_csv = exe_config / "units.csv"
    if not units_csv.is_file():
        return
    functions_csv = exe_config / FUNCTIONS_NAME
    if not functions_csv.is_file():
        raise ConfigureError(f"{units_csv} has no functions.csv beside it")
    symbols_csv = exe_config / SYMBOLS_NAME
    inputs = [functions_csv, units_csv, *([symbols_csv] if symbols_csv.is_file() else [])]
    functions = read_functions_csv(functions_csv)
    names = _exe_names(symbols_csv, functions)
    for row in read_units_csv(units_csv):
        source = src / exe / f"{row.unit}{SOURCE_SUFFIX}"
        unit_functions = tuple(f for f in functions if f.unit == row.unit)
        has_source = source.is_file()
        if has_source:
            _check_source(source, unit_functions, names=names)
        yield UnitBuild(
            exe=exe,
            exe_name=name,
            unit=_check_name("unit", row.unit),
            source=_relative(source, base) if has_source else None,
            functions=unit_functions,
            inputs=tuple(_relative(p, base) for p in inputs),
        )


def _exe_names(symbols_csv: Path, functions: Sequence[FunctionRow]) -> dict[str, int]:
    """The C names the D-12 check reads one EXE's unit files with (D-29): unitdefs.c_names of
    its functions.csv rows and its symbols.csv (optional; a missing one renames nothing)."""
    try:
        return unitdefs.c_names(functions, read_symbols_csv(symbols_csv))
    except ValueError as exc:  # a malformed row or a func name without its `_` (UnitDefsError)
        raise ConfigureError(f"{symbols_csv}: {exc}") from None


def _check_source(
    path: Path, unit_functions: Sequence[FunctionRow], *, names: Mapping[str, int] | None = None
) -> None:
    """Refuse a unit file that fails the D-12 completeness check. The bytes are read, not
    read_text: universal newlines would turn a lone CR into a line break and hide it from
    normalize_source's refusal (re-review R2-1)."""
    data = path.read_bytes()
    lone = _LONE_CR_BYTES.search(data)
    if lone is not None:
        raise ConfigureError(f"{path}: {lone_cr_problem(data.count(b'\n', 0, lone.start()) + 1)}")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ConfigureError(f"{path}: not UTF-8 ({exc})") from None
    problems = check_unit_source(text, unit_functions, all_names=names)
    if problems:
        raise ConfigureError(f"{path}: {'; '.join(problems)}")


def _check_no_stray_sources(src: Path, units: Sequence[UnitBuild]) -> None:
    """Every C file under `src` is src/<exe>/<unit>.c for a unit in that EXE's units.csv."""
    if not src.is_dir():
        return
    known = {(unit.exe, f"{unit.unit}{SOURCE_SUFFIX}") for unit in units}
    for path in sorted(src.rglob(f"*{SOURCE_SUFFIX}")):
        parts = path.relative_to(src).parts
        if len(parts) != 2 or tuple(parts) not in known:
            raise ConfigureError(
                f"{path} names no unit: a C source must be src/<exe>/<unit>.c for a unit of "
                "config/<exe>/units.csv"
            )


MANIFEST_NAME = "targets.toml"


def collect_units(config: Path, src: Path, base: Path) -> list[UnitBuild]:
    """Every units.csv row of every target of `config`/targets.toml that has
    `config`/<exe>/units.csv: the manifest comes from the same tree as the CSVs (code review
    IN-04). Raises ConfigureError for a config dir without targets.toml, a unit file that fails
    D-12 or a C file under `src` that names no unit."""
    manifest = config / MANIFEST_NAME
    if not manifest.is_file():
        raise ConfigureError(
            f"{manifest} not found: --config DIR must hold the targets.toml its CSVs belong to"
        )
    units: list[UnitBuild] = []
    for target in load_manifest(manifest):
        units += _exe_units(target.name, config, src, base)
    _check_no_stray_sources(src, units)
    return units


def _relative(path: Path, base: Path) -> str:
    try:
        return Path(os.path.relpath(path, base)).as_posix()
    except ValueError:  # different drive on Windows
        return path.resolve().as_posix()


def _encode_outputs(args: argparse.Namespace, base: Path) -> tuple[dict[Path, bytes], int, int]:
    """Every generated file's bytes, encoded before any file is opened."""
    exes = [_relative(p, base) for p in find_executables(args.orig)]
    units = collect_units(args.config, args.src, base)
    layout = Layout.for_base(
        base,
        config=args.config,
        src=args.src,
        output=args.output,
        exes=list(dict.fromkeys(unit.exe for unit in units)),
    )
    texts = {
        args.output: render(exes, orig=_relative(args.orig, base), units=units, layout=layout),
        args.output.with_name(OBJDIFF_NAME): render_objdiff(units),
        args.output.with_name(COMPILE_COMMANDS_NAME): render_compile_commands(units, base),
    }
    return {path: text.encode("utf-8") for path, text in texts.items()}, len(exes), len(units)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Write build.ninja, objdiff.json and compile_commands.json."
    )
    parser.add_argument("--orig", type=Path, default=ROOT / "orig")
    parser.add_argument("--config", type=Path, default=ROOT / DEFAULT_CONFIG)
    parser.add_argument("--src", type=Path, default=ROOT / "src")
    parser.add_argument("--output", type=Path, default=ROOT / "build.ninja")
    args = parser.parse_args(argv)
    base = args.output.resolve().parent
    try:
        # Encoded before any output is opened, so a refusal never truncates a generated file.
        data, exe_count, unit_count = _encode_outputs(args, base)
    except (ConfigureError, FunctionsError, ManifestError, UnicodeEncodeError) as exc:
        print(f"configure.py: error: {exc}", file=sys.stderr)
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    for path, payload in data.items():
        path.write_bytes(payload)
    print(
        f"wrote {args.output}, {OBJDIFF_NAME} and {COMPILE_COMMANDS_NAME} "
        f"({exe_count} executable(s) for parse-le, {unit_count} unit(s))"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
