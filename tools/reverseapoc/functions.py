"""The committed config schemas of the split, and the runtime rows that seed functions.csv.

Four files under config/<exe>/, each holding addresses, names, kinds and reasons only, never
bytes, hashes or disassembly. Every reader checks the exact header and refuses a malformed file
with a FunctionsError naming the file and its data row; a bad file is never half-read.

- functions.csv (D-10) `start,end,name,kind,unit,evidence`: one row per function or
  data-in-code range, [start, end) in linear addresses at the preferred base, written `0x%08X`,
  sorted and non-overlapping (touching rows stay separate rows). `kind` is game, runtime, thunk
  or data-in-code; `evidence` says what placed the start. Game and thunk rows are named
  func_XXXXXXXX after their start, data-in-code rows D_XXXXXXXX, runtime rows after their
  Watcom public. No match-status column: the Phase 6 status table owns status.
- boundaries.csv (D-08) `address,ghidra,capstone,evidence,verdict,reason`: every Ghidra/capstone
  disagreement, with a verdict and its reason; an empty verdict is left for a person to write.
- units.csv (D-11) `unit,start,end,reason`: the drafted translation units of the whole EXE.
- symbols.csv (D-19) `address,name,kind`: optional linker names for addresses that are neither
  func_/D_ placeholders nor runtime publics.

Runtime rows are seeded from config/<exe>/runtime.csv (Phase 4 D-06), which stays untouched:
each runtime module's range is split at the offsets of its code segment's publics, read from the
installed LIB386 at generation time.
"""

from __future__ import annotations

import bisect
import csv
import io
import re
from collections import defaultdict
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

from .libmatch import LoadedLibrary, MatchRange, _code_segments, _Owner
from .splice import _write_atomic
from .targets import config_dir


class FunctionsError(ValueError):
    """A committed config file is malformed, or a runtime row cannot be seeded."""


FUNCTIONS_CSV_COLUMNS = ("start", "end", "name", "kind", "unit", "evidence")
KINDS = ("game", "runtime", "thunk", "data-in-code")
EVIDENCE = ("call", "fixup", "entry", "runtime", "ghidra", "capstone")
FUNCTIONS_CSV_COMMENT = "# generated by: uv run reverseapoc functions {name} --write; do not edit"
KIND_GAME = "game"
KIND_RUNTIME = "runtime"
KIND_THUNK = "thunk"
KIND_DATA_IN_CODE = "data-in-code"
EVIDENCE_RUNTIME = "runtime"

BOUNDARIES_CSV_COLUMNS = ("address", "ghidra", "capstone", "evidence", "verdict", "reason")
VERDICTS = ("rule", "ghidra", "capstone", "data-in-code")
BOUNDARIES_CSV_COMMENT = (
    "# generated by: uv run reverseapoc functions {name} --write; the tool owns address, ghidra, "
    "capstone, evidence and verdict=rule; verdict and reason are written by hand where the LE "
    "evidence does not decide (D-08)"
)

UNITS_CSV_COLUMNS = ("unit", "start", "end", "reason")
UNIT_REASONS = (
    "first",
    "runtime",
    "chk-cluster",
    "source-string",
    "data-order",
    "alignment-gap",
    "hand",
)
UNITS_CSV_COMMENT = (
    "# drafted by: uv run reverseapoc units {name} --write; a draft (D-11), re-cut by hand when a "
    "unit is wrong (reason=hand)"
)

SYMBOLS_CSV_COLUMNS = ("address", "name", "kind")
SYMBOL_KINDS = ("func", "data")
SYMBOLS_CSV_COMMENT = (
    "# linker names for addresses that are neither func_/D_ placeholders nor runtime publics "
    "(D-19); addresses and names only"
)

# Placeholder names (docs/coding-style.md): the linear address as 8 uppercase hex digits.
GAME_PREFIX = "func_"
DATA_PREFIX = "D_"
ADDRESS_DIGITS = 8
RUNTIME_VERSION = "10.6"  # Phase 4: the linked runtime is 10.6
_ADDRESS_FORMAT = f"0x{{:0{ADDRESS_DIGITS}X}}"
_PLACEHOLDER_FORMAT = f"{{}}{{:0{ADDRESS_DIGITS}X}}"
_UNIT_NAME = re.compile(r"[a-z0-9_]+")
_LINKER_NAME = re.compile(r"[A-Za-z_$?@.][A-Za-z0-9_$?@.]*")  # a Watcom public, as wlink sees it
_LIST_SEPARATOR = ";"
_YES, _NO = "yes", "no"
_ALTERNATIVE_SEPARATOR = "@"  # runtime.csv alternatives are module@library


def game_name(start: int) -> str:
    """func_XXXXXXXX: the C name of a game or thunk function starting at `start`."""
    return _PLACEHOLDER_FORMAT.format(GAME_PREFIX, start)


def data_name(address: int) -> str:
    """D_XXXXXXXX: the C name of the data at `address`."""
    return _PLACEHOLDER_FORMAT.format(DATA_PREFIX, address)


@dataclass(frozen=True)
class FunctionRow:
    """One functions.csv row: [start, end) in linear addresses."""

    start: int
    end: int
    name: str
    kind: str
    unit: str
    evidence: str


# ---- shared CSV plumbing ----


def _address(value: int) -> str:
    return _ADDRESS_FORMAT.format(value)


def _format_csv(comment: str, columns: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    buf = io.StringIO()
    buf.write(comment + "\n")
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(columns)
    writer.writerows(rows)
    return buf.getvalue()


def _write_text(path: Path, text: str) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    _write_atomic(path, text.encode("utf-8"))


def _read_records(path: Path, columns: Sequence[str]) -> list[dict[str, str]]:
    """The data rows of a committed CSV as dicts; comment lines (starting with #) are skipped.
    A file that is not UTF-8 or whose header is not exactly `columns` is refused."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except UnicodeDecodeError as exc:
        raise FunctionsError(f"{path}: not UTF-8 ({exc})") from exc
    lines = [line for line in text.splitlines() if not line.startswith("#")]
    reader = csv.DictReader(lines)
    if tuple(reader.fieldnames or ()) != tuple(columns):
        raise FunctionsError(f"{path}: header is not {','.join(columns)}")
    return list(reader)


def _load[Row](
    path: Path,
    columns: Sequence[str],
    parse: Callable[[dict[str, str]], Row],
    follows: Callable[[list[Row], Row], None],
) -> list[Row]:
    """Parse every data row of a committed CSV; `follows(earlier_rows, row)` checks a row
    against the rows before it. Any problem raises FunctionsError naming the file and the data
    row number (1 = the first row after the header)."""
    rows: list[Row] = []
    for number, record in enumerate(_read_records(path, columns), start=1):
        try:
            if None in record:
                raise ValueError("more fields than the header")
            row = parse(record)
            follows(rows, row)
        except (TypeError, ValueError) as exc:
            raise FunctionsError(f"{path}: data row {number}: {exc}") from exc
        rows.append(row)
    return rows


def _cell(record: dict[str, str], column: str) -> str:
    return record[column] or ""


def _parse_address(record: dict[str, str], column: str) -> int:
    cell = _cell(record, column)
    try:
        return int(cell, 16)
    except ValueError:
        raise ValueError(f"{column} {cell!r} is not a hex address") from None


def _check_choice(column: str, value: str, allowed: Sequence[str]) -> None:
    if value not in allowed:
        raise ValueError(f"{column} {value!r} is not one of {', '.join(allowed)}")


def _check_range(start: int, end: int) -> None:
    if start >= end:
        raise ValueError(f"start {_address(start)} is not below end {_address(end)}")


def _check_after(previous_start: int, previous_end: int, start: int) -> None:
    """Rows are sorted by start and never overlap; touching rows are fine."""
    if start < previous_start:
        raise ValueError(
            f"start {_address(start)} is out of order (after {_address(previous_start)})"
        )
    if start < previous_end:
        raise ValueError(
            f"start {_address(start)} overlaps the row ending at {_address(previous_end)}"
        )


def _check_linker_name(name: str) -> None:
    if not _LINKER_NAME.fullmatch(name):
        raise ValueError(f"name {name!r} is not a linker name")


# ---- functions.csv (D-10) ----


def _function_cells(row: FunctionRow) -> list[str]:
    return [_address(row.start), _address(row.end), row.name, row.kind, row.unit, row.evidence]


def format_functions_csv(rows: Iterable[FunctionRow], name: str) -> str:
    """The functions.csv text: the generated-by comment, the header, one line per row."""
    return _format_csv(FUNCTIONS_CSV_COMMENT.format(name=name), FUNCTIONS_CSV_COLUMNS,
                       (_function_cells(r) for r in rows))  # fmt: skip


def write_functions_csv(path: Path, rows: Iterable[FunctionRow], name: str) -> None:
    """Write format_functions_csv atomically, creating the parent directories."""
    _write_text(path, format_functions_csv(rows, name))


def _check_function_name(row: FunctionRow) -> None:
    """Game and thunk rows are func_<start>, data-in-code rows D_<start>, runtime rows a public."""
    expected = {
        KIND_GAME: game_name(row.start),
        KIND_THUNK: game_name(row.start),
        KIND_DATA_IN_CODE: data_name(row.start),
    }.get(row.kind)
    if expected is None:
        _check_linker_name(row.name)
    elif row.name != expected:
        raise ValueError(f"name {row.name!r} of a {row.kind} row should be {expected}")


def _check_unit_cell(unit: str) -> None:
    """Empty (not drafted yet, orchestrator ruling F1) or a unit name."""
    if unit and not _UNIT_NAME.fullmatch(unit):
        raise ValueError(f"unit {unit!r} is not [a-z0-9_]+")


def _parse_function(record: dict[str, str]) -> FunctionRow:
    row = FunctionRow(
        start=_parse_address(record, "start"),
        end=_parse_address(record, "end"),
        name=_cell(record, "name"),
        kind=_cell(record, "kind"),
        unit=_cell(record, "unit"),
        evidence=_cell(record, "evidence"),
    )
    _check_range(row.start, row.end)
    _check_choice("kind", row.kind, KINDS)
    _check_choice("evidence", row.evidence, EVIDENCE)
    _check_function_name(row)
    _check_unit_cell(row.unit)
    return row


def _function_follows(rows: list[FunctionRow], row: FunctionRow) -> None:
    if rows:
        _check_after(rows[-1].start, rows[-1].end, row.start)


def read_functions_csv(path: Path) -> list[FunctionRow]:
    """The rows of a functions.csv, validated (see the module docstring)."""
    return _load(path, FUNCTIONS_CSV_COLUMNS, _parse_function, _function_follows)


def functions_csv_path(name: str) -> Path:
    """config/<stem>/functions.csv for a manifest name."""
    return config_dir(name) / "functions.csv"


# ---- boundaries.csv (D-08) ----


@dataclass(frozen=True)
class BoundaryRow:
    """One Ghidra/capstone disagreement at a candidate function start."""

    address: int
    ghidra: bool  # Ghidra starts a function here
    capstone: bool  # the capstone sweep starts a function here
    evidence: tuple[str, ...]  # a subset of EVIDENCE
    verdict: str  # one of VERDICTS, or empty until a person decides
    reason: str


def _flag(value: bool) -> str:
    return _YES if value else _NO


def _parse_flag(record: dict[str, str], column: str) -> bool:
    cell = _cell(record, column)
    if cell not in (_YES, _NO):
        raise ValueError(f"{column} {cell!r} is not {_YES} or {_NO}")
    return cell == _YES


def _boundary_cells(row: BoundaryRow) -> list[str]:
    return [_address(row.address), _flag(row.ghidra), _flag(row.capstone),
            _LIST_SEPARATOR.join(row.evidence), row.verdict, row.reason]  # fmt: skip


def format_boundaries_csv(rows: Iterable[BoundaryRow], name: str) -> str:
    """The boundaries.csv text: the generated-by comment, the header, one line per row."""
    return _format_csv(BOUNDARIES_CSV_COMMENT.format(name=name), BOUNDARIES_CSV_COLUMNS,
                       (_boundary_cells(r) for r in rows))  # fmt: skip


def write_boundaries_csv(path: Path, rows: Iterable[BoundaryRow], name: str) -> None:
    """Write format_boundaries_csv atomically, creating the parent directories."""
    _write_text(path, format_boundaries_csv(rows, name))


def _parse_boundary(record: dict[str, str]) -> BoundaryRow:
    evidence_cell = _cell(record, "evidence")
    row = BoundaryRow(
        address=_parse_address(record, "address"),
        ghidra=_parse_flag(record, "ghidra"),
        capstone=_parse_flag(record, "capstone"),
        evidence=tuple(evidence_cell.split(_LIST_SEPARATOR)) if evidence_cell else (),
        verdict=_cell(record, "verdict"),
        reason=_cell(record, "reason"),
    )
    for item in row.evidence:
        _check_choice("evidence", item, EVIDENCE)
    if row.verdict:
        _check_choice("verdict", row.verdict, VERDICTS)
    if row.verdict and not row.reason:
        raise ValueError(f"verdict {row.verdict} needs a reason")
    return row


def _boundary_follows(rows: list[BoundaryRow], row: BoundaryRow) -> None:
    if not rows:
        return
    previous = rows[-1].address
    if row.address == previous:
        raise ValueError(f"address {_address(row.address)} is listed twice")
    if row.address < previous:
        raise ValueError(f"address {_address(row.address)} is out of order")


def read_boundaries_csv(path: Path) -> list[BoundaryRow]:
    """The rows of a boundaries.csv: addresses unique and sorted, a verdict needs a reason."""
    return _load(path, BOUNDARIES_CSV_COLUMNS, _parse_boundary, _boundary_follows)


def missing_verdicts(rows: Iterable[BoundaryRow]) -> list[int]:
    """The addresses of every disagreement nobody has decided yet (D-08: must be empty)."""
    return [row.address for row in rows if not row.verdict]


def boundaries_csv_path(name: str) -> Path:
    """config/<stem>/boundaries.csv for a manifest name."""
    return config_dir(name) / "boundaries.csv"


# ---- units.csv (D-11) ----


@dataclass(frozen=True)
class UnitRow:
    """One drafted translation unit: [start, end) and the evidence for its cut."""

    unit: str
    start: int
    end: int
    reason: str  # one of UNIT_REASONS


def _unit_cells(row: UnitRow) -> list[str]:
    return [row.unit, _address(row.start), _address(row.end), row.reason]


def format_units_csv(rows: Iterable[UnitRow], name: str) -> str:
    """The units.csv text: the drafted-by comment, the header, one line per unit."""
    return _format_csv(UNITS_CSV_COMMENT.format(name=name), UNITS_CSV_COLUMNS,
                       (_unit_cells(r) for r in rows))  # fmt: skip


def write_units_csv(path: Path, rows: Iterable[UnitRow], name: str) -> None:
    """Write format_units_csv atomically, creating the parent directories."""
    _write_text(path, format_units_csv(rows, name))


def _parse_unit(record: dict[str, str]) -> UnitRow:
    row = UnitRow(
        unit=_cell(record, "unit"),
        start=_parse_address(record, "start"),
        end=_parse_address(record, "end"),
        reason=_cell(record, "reason"),
    )
    if not _UNIT_NAME.fullmatch(row.unit):
        raise ValueError(f"unit {row.unit!r} is not [a-z0-9_]+")
    _check_range(row.start, row.end)
    _check_choice("reason", row.reason, UNIT_REASONS)
    return row


def _unit_follows(rows: list[UnitRow], row: UnitRow) -> None:
    if any(earlier.unit == row.unit for earlier in rows):
        raise ValueError(f"duplicate unit name {row.unit}")
    if rows:
        _check_after(rows[-1].start, rows[-1].end, row.start)


def read_units_csv(path: Path) -> list[UnitRow]:
    """The rows of a units.csv: names unique and [a-z0-9_]+, sorted, non-overlapping."""
    return _load(path, UNITS_CSV_COLUMNS, _parse_unit, _unit_follows)


def units_csv_path(name: str) -> Path:
    """config/<stem>/units.csv for a manifest name."""
    return config_dir(name) / "units.csv"


def _unit_at(units: Sequence[UnitRow], starts: Sequence[int], va: int) -> UnitRow | None:
    """The unit holding `va`; `units` sorted and non-overlapping, `starts` their starts."""
    index = bisect.bisect_right(starts, va) - 1
    if index < 0 or va >= units[index].end:
        return None
    return units[index]


def _assignment_problem(
    row: FunctionRow, units: Sequence[UnitRow], starts: Sequence[int]
) -> str | None:
    first = _unit_at(units, starts, row.start)
    last = _unit_at(units, starts, row.end - 1)
    where = f"{row.name} at {_address(row.start)}"
    if first is None and last is None:
        return f"{where}: outside every unit"
    if first is not last:
        names = " and ".join(u.unit if u else "no unit" for u in (first, last))
        return f"{where}: spans {names}"
    if row.unit != first.unit:
        return f"{where}: unit column is {row.unit!r} but it lies in unit {first.unit}"
    return None


def check_unit_assignment(functions: Sequence[FunctionRow], units: Sequence[UnitRow]) -> list[str]:
    """One problem per function outside every unit, spanning two units, or whose unit column
    differs from the unit holding it (D-11: every function is in exactly one unit)."""
    ordered = sorted(units, key=lambda u: u.start)
    starts = [u.start for u in ordered]
    problems = (_assignment_problem(row, ordered, starts) for row in functions)
    return [problem for problem in problems if problem is not None]


# ---- symbols.csv (D-19) ----


@dataclass(frozen=True)
class SymbolRow:
    """One linker name for an address that is neither a placeholder nor a runtime public."""

    address: int
    name: str
    kind: str  # one of SYMBOL_KINDS


def _symbol_cells(row: SymbolRow) -> list[str]:
    return [_address(row.address), row.name, row.kind]


def format_symbols_csv(rows: Iterable[SymbolRow], name: str) -> str:
    """The symbols.csv text: the comment, the header, one line per symbol (`name` is the EXE,
    accepted for symmetry with the other writers)."""
    return _format_csv(SYMBOLS_CSV_COMMENT.format(name=name), SYMBOLS_CSV_COLUMNS,
                       (_symbol_cells(r) for r in rows))  # fmt: skip


def write_symbols_csv(path: Path, rows: Iterable[SymbolRow], name: str) -> None:
    """Write format_symbols_csv atomically, creating the parent directories."""
    _write_text(path, format_symbols_csv(rows, name))


def _parse_symbol(record: dict[str, str]) -> SymbolRow:
    row = SymbolRow(
        address=_parse_address(record, "address"),
        name=_cell(record, "name"),
        kind=_cell(record, "kind"),
    )
    _check_linker_name(row.name)
    _check_choice("kind", row.kind, SYMBOL_KINDS)
    return row


def _symbol_follows(rows: list[SymbolRow], row: SymbolRow) -> None:
    if any(earlier.address == row.address for earlier in rows):
        raise ValueError(f"address {_address(row.address)} is listed twice")
    if any(earlier.name == row.name for earlier in rows):
        raise ValueError(f"name {row.name} is listed twice")


def read_symbols_csv(path: Path) -> list[SymbolRow]:
    """The rows of a symbols.csv; the file is optional, so a missing one reads as no rows."""
    if not Path(path).exists():
        return []
    return _load(path, SYMBOLS_CSV_COLUMNS, _parse_symbol, _symbol_follows)


def symbols_csv_path(name: str) -> Path:
    """config/<stem>/symbols.csv for a manifest name."""
    return config_dir(name) / "symbols.csv"


# ---- runtime seeding (Phase 4 D-06) ----


@dataclass(frozen=True)
class RuntimeEntry:
    """One entry point of a runtime module: [start, end) and every public placed at start."""

    start: int
    end: int
    aliases: tuple[str, ...]  # sorted

    @property
    def name(self) -> str:
        """The row's name (orchestrator ruling F12): the alias without a leading underscore,
        else the first in sorted order."""
        plain = [alias for alias in self.aliases if not alias.startswith("_")]
        return (plain or list(self.aliases))[0]


def _row_version(row: MatchRange, version: str) -> str:
    if version in row.versions:
        return version
    if not row.versions:
        raise FunctionsError(f"runtime row {row.describe()} lists no version")
    return row.versions[0]


def _candidate_modules(row: MatchRange) -> set[tuple[str, str]]:
    """(module, library) pairs that matched the row: its module in every library it lists, and
    each alternative. The module named in runtime.csv may be another version's THEADR name."""
    pairs = {(row.module, library) for library in row.libraries}
    for alternative in row.alternatives:
        module, _, library = alternative.partition(_ALTERNATIVE_SEPARATOR)
        pairs.add((module, library))
    return pairs


def _row_owners(row: MatchRange, owners: Sequence[_Owner], version: str) -> list[_Owner]:
    """The code segments of `version` that runtime.csv placed at `row`."""
    pairs = _candidate_modules(row)
    length = row.end - row.start
    found = [
        owner
        for owner in owners
        if owner.version == version
        and (owner.module_name, owner.library) in pairs
        and owner.segment.length == length
    ]
    if not found:
        raise FunctionsError(
            f"runtime row {row.describe()}: no {version} code segment of length {length:#x} "
            f"for module {row.module} in {', '.join(row.libraries)}"
        )
    return found


def _offset_aliases(row: MatchRange, owners: Iterable[_Owner]) -> dict[int, set[str]]:
    """Segment offset -> the row's publics placed there, over every matching segment (identical
    bytes, so the segments share their public offsets). A public at or past the segment end is
    an end label (___GETDSEnd_), not an entry point, and never becomes a zero-length row."""
    wanted = set(row.publics)
    length = row.end - row.start
    by_offset: dict[int, set[str]] = defaultdict(set)
    for owner in owners:
        for public in owner.segment_publics:
            if public.name not in wanted or public.offset >= length:
                continue
            by_offset[public.offset].add(public.name)
    return by_offset


def _row_entries(row: MatchRange, owners: Sequence[_Owner], version: str) -> list[RuntimeEntry]:
    by_offset = _offset_aliases(row, _row_owners(row, owners, version))
    starts = sorted(row.start + offset for offset in by_offset)
    ends = [*starts[1:], row.end]
    return [
        RuntimeEntry(start, end, tuple(sorted(by_offset[start - row.start])))
        for start, end in zip(starts, ends, strict=True)
    ]


def runtime_entries(
    runtime: Sequence[MatchRange],
    libraries: Sequence[LoadedLibrary],
    *,
    version: str = RUNTIME_VERSION,
) -> list[RuntimeEntry]:
    """One entry per distinct public offset of each runtime.csv row's code segment, read from
    `libraries` at `version` (or the row's first version when it does not list `version`).
    Bytes before a module's first public belong to no entry."""
    owners = list(_code_segments(libraries))
    entries: list[RuntimeEntry] = []
    for row in runtime:
        entries += _row_entries(row, owners, _row_version(row, version))
    return entries


def seed_runtime_rows(
    runtime: Sequence[MatchRange],
    libraries: Sequence[LoadedLibrary],
    *,
    version: str = RUNTIME_VERSION,
) -> list[FunctionRow]:
    """The runtime rows of functions.csv: one per runtime_entries entry, named by its F12 name,
    kind and evidence `runtime`, unit empty until units are drafted."""
    return [
        FunctionRow(e.start, e.end, e.name, KIND_RUNTIME, "", EVIDENCE_RUNTIME)
        for e in runtime_entries(runtime, libraries, version=version)
    ]


def runtime_aliases(entries: Iterable[RuntimeEntry]) -> dict[str, int]:
    """Every public of every entry -> the entry's start, so SymbolTable.address_of resolves the
    aliases a seeded row is not named after (F12: malloc_ and _nmalloc_ name one row)."""
    return {alias: entry.start for entry in entries for alias in entry.aliases}
