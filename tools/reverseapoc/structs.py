SIGNED, UNSIGNED, REAL = "s", "u", "f"
_SIGN_NOTES = {SIGNED: "sign-extended", UNSIGNED: "zero-extended", REAL: "x87 real"}
_SIGN_UNKNOWN = "sign unknown"
_EXTENDS = {"movsx": SIGNED, "movzx": UNSIGNED}
_X87 = "f"  # every x87 mnemonic starts with it
_X87_INTEGER = "fi"  # fild, fist, fistp, fiadd, ficom...: a signed integer in memory
_STRING_OPS = frozenset(f"{op}{size}" for op in ("movs", "stos", "lods", "cmps", "scas")
                        for size in "bwd")  # fmt: skip
_MOVES = frozenset({"add", "sub"})  # an immediate moves a held base's offset
_SIGN_BIT = 1 << 31
_WORD_MASK = (1 << 32) - 1


class StructsError(ValueError):
    """structs.json cannot be read as shapes."""


@dataclass(frozen=True, slots=True, order=True)
class Base:
    """What a base pointer is: `kind` (ARG, RESULT, POINTER or OBJECT), the row start (ARG,
    RESULT) or the global's address (POINTER, OBJECT), and the argument's place in
    lift.ARG_REGS (ARG)."""

    kind: str
    va: int
    index: int = 0

    def rank(self) -> tuple[int, int, int]:
        return KINDS.index(self.kind), self.va, self.index

    def label(self) -> str:
        where = f"0x{self.va:08X}"
        return f"{where} arg {self.index}" if self.kind == ARG else f"{where} {self.kind}"


@dataclass(frozen=True, slots=True)
class Access:
    base: Base
    offset: int
    width: int
    sign: str  # SIGNED, UNSIGNED, REAL or ""
    stride: int  # the index scale, 0 for none
    function: int  # the row start


@dataclass(frozen=True, slots=True)
class Field:
    """Every access at one offset and width: how it is read (the signs seen, joined, "" for
    plain moves), the index scales seen and the row starts that make it."""

    offset: int
    width: int
    sign: str
    strides: tuple[int, ...]
    functions: tuple[int, ...]


@dataclass(frozen=True, slots=True)
class Shape:
    name: str
    bases: tuple[Base, ...]
    fields: tuple[Field, ...]  # by offset, then width

    @property
    def functions(self) -> tuple[int, ...]:
        return tuple(sorted({va for f in self.fields for va in f.functions}))

    @property
    def size(self) -> int:
        """The bytes up to the end of the last field (at least that big)."""
        return max((f.offset + f.width for f in self.fields), default=0)


@dataclass(frozen=True, slots=True)
class Shapes:
    exe: str  # the stem
    shapes: tuple[Shape, ...]  # by name
    rows: int  # game and thunk rows read
    skipped: int  # of them, the rows the lifter's front end refuses
    bases: int  # distinct bases with a field access
    links: int  # joins made across functions
    refused: int  # joins refused (one offset at different widths)


# ---- one row ----


def _signed(value: int) -> int:
    """`value` as a signed 32-bit number."""
    value &= _WORD_MASK
    return value - (1 << 32) if value & _SIGN_BIT else value


def _sign(mnemonic: str) -> str:
    if mnemonic in _EXTENDS:
        return _EXTENDS[mnemonic]
    if mnemonic.startswith(_X87_INTEGER):
        return SIGNED
    return REAL if mnemonic.startswith(_X87) else ""


Held = tuple[Base, int]  # a base and the offset from it a register holds
State = dict[str, Held]


def _meet(states: Sequence[State]) -> State:
    first, rest = states[0], states[1:]
    return {reg: held for reg, held in first.items() if all(s.get(reg) == held for s in rest)}


class _Row:
    """The forward pass over one row's blocks; `accesses` and `links` are what the last run
    over the settled block states found."""

    def __init__(
        self, exe: Any, row: FunctionRow, sigs: dict[int, lift.Sig | None], walked: frozenset[int]
    ) -> None:
        self.row, self.walked = row, walked
        self.lifter = lift.Lifter(exe, row, sigs)
        self.accesses: list[Access] = []
        self.links: list[tuple[Base, Base]] = []
        self.record = False
        self.own: lift.Sig | None = None

    def _signature(self, va: int) -> lift.Sig | None:
        """The signature of the walked row at `va` (lift's memo), or None."""
        if va not in self.walked:
            return None
        try:
            return self.lifter.callee(va)[1]
        except lift.Unliftable:
            return None

    def scan(self) -> bool:
        """False when lift's front end refuses the row."""
        try:
            _, _, _, blocks, order, _, _ = self.lifter.prepare(frozenset(), strict=False)
        except lift.Unliftable:
            return False
        self.own = self._signature(self.row.start)
        nregs = min(self.own.nregs, len(lift.ARG_REGS)) if self.own else 0
        entry = {reg: (Base(ARG, self.row.start, k), 0)
                 for k, reg in enumerate(lift.ARG_REGS[:nregs])}  # fmt: skip
        ins = self._settle(blocks, order, entry)
        self.record = True
        for start in order:
            if start in ins:
                self._run(blocks[start].insns, ins[start])
        return True

    def _settle(self, blocks: Mapping[int, Any], order: Sequence[int], entry: State) -> dict:
        """Each reachable block's entry state, iterated until no block's exit state changes."""
        preds: defaultdict[int, list[int]] = defaultdict(list)
        for start in order:
            for succ in blocks[start].succ:
                preds[succ].append(start)
        ins: dict[int, State] = {}
        outs: dict[int, State] = {}
        changed = True
        while changed:
            changed = False
            for start in order:
                sources = [entry] if start == order[0] else []
                sources += [outs[p] for p in preds[start] if p in outs]
                if not sources:
                    continue
                ins[start] = _meet(sources)
                out = self._run(blocks[start].insns, ins[start])
                if outs.get(start) != out:
                    outs[start] = out
                    changed = True
        return ins

    def _run(self, insns: Iterable[Any], state: State) -> State:
        state = dict(state)
        for ci in insns:
            self._step(ci, state)
        return state

    def _step(self, ci: Any, state: State) -> None:
        if self.record:
            self.accesses += self._accesses(ci, state)
        held = self._held(ci, state)
        result = self._call(ci, state)
        if self.record and ci.mnemonic == "ret":
            self._returned(state)
        for reg in lift._use_def(ci)[1]:
            state.pop(reg, None)
        for reg, value in (*held, *result):
            state[reg] = value

    # -- what an instruction reads --

    def _fixup(self, ci: Any, offset: int) -> Any:
        return self.lifter.fix.get(ci.address + offset) if offset else None

    def _accesses(self, ci: Any, state: State) -> Iterator[Access]:
        if ci.mnemonic == "lea" or ci.mnemonic in _STRING_OPS:
            return
        if self._fixup(ci, ci.disp_offset) is not None:
            return  # the displacement is an address: an array, not a field
        for op in ci.operands:
            if op.type != X86_OP_MEM or op.mem.segment != X86_REG_INVALID:
                continue
            found = self._base_of(ci, op.mem, state)
            if found is None:
                continue
            (base, delta), stride = found
            yield Access(base, delta + _signed(op.mem.disp), op.size, _sign(ci.mnemonic),
                         stride, self.row.start)  # fmt: skip

    @staticmethod
    def _base_of(ci: Any, mem: Any, state: State) -> tuple[Held, int] | None:
        """The held base of a memory operand and its index scale (0: no index). An unscaled
        index register can hold the base when the base register does not."""
        base = ci.reg_name(mem.base) if mem.base else None
        index = ci.reg_name(mem.index) if mem.index else None
        if base in state:
            return state[base], mem.scale if index else 0
        if index in state and mem.scale == 1:
            return state[index], 1 if base else 0
        return None

    # -- what an instruction writes --

    def _data(self, fixup: Any) -> int | None:
        """The target of a fixup that addresses data, not code."""
        if fixup is None or self.lifter._is_code(fixup.target_va):
            return None
        return fixup.target_va

    def _held(self, ci: Any, state: State) -> tuple[tuple[str, Held], ...]:
        """The register a copy, a global read or an offset move leaves holding a base."""
        ops = ci.operands
        if len(ops) != 2:
            return ()
        dest = lift._full_reg(ci, ops[0])
        if dest is None:
            return ()
        value = self._value(ci, dest, ops[1], state)
        return ((dest, value),) if value is not None else ()

    def _value(self, ci: Any, dest: str, src: Any, state: State) -> Held | None:
        if ci.mnemonic == "mov":
            return self._moved(ci, src, state)
        if ci.mnemonic == "lea":
            return self._address(ci, src, state)
        if ci.mnemonic in _MOVES and dest in state and src.type == X86_OP_IMM:
            if self._fixup(ci, ci.imm_offset) is not None:
                return None
            base, delta = state[dest]
            step = _signed(src.imm)
            return base, delta + (step if ci.mnemonic == "add" else -step)
        return None

    def _moved(self, ci: Any, src: Any, state: State) -> Held | None:
        reg = lift._full_reg(ci, src)
        if reg is not None:
            return state.get(reg)
        if src.type == X86_OP_IMM:
            target = self._data(self._fixup(ci, ci.imm_offset))
            return (Base(OBJECT, target), 0) if target is not None else None
        if src.type != X86_OP_MEM or src.mem.base or src.mem.index or src.size != lift.DWORD:
            return None
        target = self._data(self._fixup(ci, ci.disp_offset))
        return (Base(POINTER, target), 0) if target is not None else None

    def _address(self, ci: Any, src: Any, state: State) -> Held | None:
        mem = src.mem
        fixup = self._fixup(ci, ci.disp_offset)
        if mem.index:
            return None
        if not mem.base:
            target = self._data(fixup)
            return (Base(OBJECT, target), 0) if target is not None else None
        base = ci.reg_name(mem.base)
        if fixup is not None or base not in state:
            return None
        held, delta = state[base]
        return held, delta + _signed(mem.disp)

    # -- calls and returns --

    def _call(self, ci: Any, state: State) -> tuple[tuple[str, Held], ...]:
        """Join the arguments a direct call or tail jump passes; a call's result is eax."""
        if ci.mnemonic != "call" and not self.lifter._tail_jump(ci):
            return ()
        target = lift._branch_target(ci)
        sig = self._signature(target) if target is not None else None
        if sig is None:
            return ()
        if self.record:
            for k, reg in enumerate(lift.ARG_REGS[: min(sig.nregs, len(lift.ARG_REGS))]):
                held = state.get(reg)
                if held is not None and held[1] == 0:
                    self.links.append((held[0], Base(ARG, target, k)))
        return (("eax", (Base(RESULT, target), 0)),) if ci.mnemonic == "call" else ()

    def _returned(self, state: State) -> None:
        """eax at a `ret` joins the row's result when its signature returns and some caller
        reads that result (lift's census): a void row's eax is whatever its last write left,
        and joining it could merge two unrelated bases."""
        held = state.get("eax")
        if held is None or held[1] != 0 or self.own is None or not self.own.returns:
            return
        census = lift.result_used(self.lifter.exe)
        if census is not None and self.row.start in census[0]:
            self.links.append((held[0], Base(RESULT, self.row.start)))


# ---- across rows ----


class _Classes:
    """Union-find over bases, with each class's widths per offset (the join check)."""

    def __init__(self) -> None:
        self.parent: dict[Base, Base] = {}
        self.widths: dict[Base, defaultdict[int, set[int]]] = {}

    def add(self, base: Base) -> None:
        if base not in self.parent:
            self.parent[base] = base
            self.widths[base] = defaultdict(set)

    def find(self, base: Base) -> Base:
        self.add(base)
        while self.parent[base] != base:
            self.parent[base] = self.parent[self.parent[base]]
            base = self.parent[base]
        return base

    def union(self, a: Base, b: Base) -> bool | None:
        """Join the classes of `a` and `b`: True when joined, False when refused (an offset
        read only at different widths), None when they are one class already."""
        ra, rb = self.find(a), self.find(b)
        if ra == rb:
            return None
        wa, wb = self.widths[ra], self.widths[rb]
        if any(not wa[offset] & wb[offset] for offset in wa.keys() & wb.keys()):
            return False
        keep, gone = sorted((ra, rb), key=Base.rank)
        self.parent[gone] = keep
        for offset, widths in self.widths.pop(gone).items():
            self.widths[keep][offset] |= widths
        return True


def _fields(accesses: Iterable[Access]) -> tuple[Field, ...]:
    grouped: defaultdict[tuple[int, int], list[Access]] = defaultdict(list)
    for access in accesses:
        grouped[access.offset, access.width].append(access)
    return tuple(Field(offset, width, "".join(sorted({a.sign for a in group} - {""})),
                       tuple(sorted({a.stride for a in group} - {0})),
                       tuple(sorted({a.function for a in group})))
                 for (offset, width), group in sorted(grouped.items()))  # fmt: skip


def _name(base: Base, symbols: Any) -> str:
    if base.kind == OBJECT:
        return f"shape_{symbols.c_name(base.va, data=True)}"
    if base.kind == POINTER:
        return f"shape_{symbols.c_name(base.va, data=True)}_target"
    suffix = f"arg{base.index}" if base.kind == ARG else "ret"
    return f"shape_{symbols.c_name(base.va)}_{suffix}"


def _scan_rows(exe: Any) -> tuple[list[Access], list[tuple[Base, Base]], int, int]:
    """Every access and join of the EXE's game and thunk rows, the rows read and skipped."""
    rows = [row for row in exe.rows if row.kind in WALKED_KINDS]
    walked = frozenset(row.start for row in rows)
    sigs: dict[int, lift.Sig | None] = {}
    accesses: list[Access] = []
    links: list[tuple[Base, Base]] = []
    skipped = 0
    for row in rows:
        scan = _Row(exe, row, sigs, walked)
        if not scan.scan():
            skipped += 1
            continue
        accesses += scan.accesses
        links += scan.links
    return accesses, links, len(rows), skipped


def _used(links: Sequence[tuple[Base, Base]], accessed: Iterable[Base]) -> set[Base]:
    """The arguments some function dereferences: their own row, or a callee they are passed
    on to with offset 0, however deep."""
    used = {base for base in accessed if base.kind == ARG}
    passed: defaultdict[Base, list[Base]] = defaultdict(list)
    for held, callee in links:
        if callee.kind == ARG and held.kind == ARG:
            passed[callee].append(held)
    todo = list(used)
    while todo:
        for held in passed[todo.pop()]:
            if held not in used:
                used.add(held)
                todo.append(held)
    return used


def analyze(exe: Any) -> Shapes:
    """The struct shapes of `exe` (check.ExeInputs, or any object with its flat, rows, fixups,
    symbols and stem), from every game and thunk row (module docstring). A link into an
    argument no function dereferences is dropped: lift's signature counts every register up
    to the last one read, so such an argument may be no argument at all, and every caller's
    leftover register would meet in it."""
    accesses, links, rows, skipped = _scan_rows(exe)
    used = _used(links, (access.base for access in accesses))
    links = [(held, to) for held, to in links if to.kind != ARG or to in used]
    classes = _Classes()
    for access in accesses:
        classes.widths[classes.find(access.base)][access.offset].add(access.width)
    joined = [classes.union(a, b) for a, b in sorted(set(links))]
    members: defaultdict[Base, list[Base]] = defaultdict(list)
    for base in list(classes.parent):
        members[classes.find(base)].append(base)
    by_base: defaultdict[Base, list[Access]] = defaultdict(list)
    for access in accesses:
        by_base[access.base].append(access)
    shapes = []
    for bases in members.values():
        fields = _fields(a for base in bases for a in by_base.get(base, ()))
        if len({f.offset for f in fields}) < MIN_FIELDS:
            continue
        ordered = tuple(sorted(bases, key=Base.rank))
        shapes.append(Shape(_name(ordered[0], exe.symbols), ordered, fields))
    return Shapes(exe.stem, tuple(sorted(shapes, key=lambda s: s.name)), rows, skipped,
                  len(by_base), joined.count(True), joined.count(False))  # fmt: skip


# ---- text ----


def _n(count: int, word: str) -> str:
    return f"{count} {word}{'' if count == 1 else 's'}"


def _offset(offset: int) -> str:
    return f"{'-' if offset < 0 else '+'}0x{abs(offset):04X}"


def _c_type(field: Field) -> str | None:
    """The C89 type of a field's width and reading (lift.SIZE_TYPE), None when it has none."""
    kind = lift.FLOAT if field.sign == REAL else field.sign != UNSIGNED
    return lift.SIZE_TYPE.get((field.width, kind))


def _type_text(field: Field) -> str:
    found = _c_type(field)
    return found if found is not None else f"unsigned char[{field.width}]"


def _counted(functions: Sequence[int], matched: frozenset[int]) -> str:
    return f"{_n(len(functions), 'function')} ({sum(va in matched for va in functions)} matched)"


def _sign_unknown(field: Field) -> bool:
    """A narrow field only ever read by plain moves: its C type's sign is a guess."""
    return not field.sign and field.width < lift.FULL_WIDTH


def _notes(field: Field, matched: frozenset[int]) -> str:
    notes = [_SIGN_NOTES.get(sign, sign) for sign in field.sign]
    notes += [_SIGN_UNKNOWN] if _sign_unknown(field) else []
    notes += [f"indexed, scale {stride}" for stride in field.strides]
    return "; ".join([*notes, _counted(field.functions, matched)])


def _declaration(field: Field, matched: frozenset[int]) -> str:
    found = _c_type(field)
    name = f"f_{field.offset:04X}"
    text = f"{found} {name}" if found is not None else f"unsigned char {name}[{field.width}]"
    return f"    {text}; /* {_notes(field, matched)} */"


def _layout(fields: Sequence[Field], matched: frozenset[int]) -> Iterator[str]:
    """The member lines: at each offset the field most functions read (then the widest), with
    padding before it; the rest at that offset, and every field that starts inside one already
    laid out (or before offset 0), as comments."""
    cursor = 0
    for offset, group in groupby(fields, key=lambda f: f.offset):
        ranked = sorted(group, key=lambda f: (-len(f.functions), -f.width))
        if offset < cursor or offset < 0:
            for f in ranked:
                yield (f"    /* {_offset(offset)}: {_n(f.width, 'byte')}, overlaps "
                       f"({_notes(f, matched)}) */")  # fmt: skip
            continue
        if offset > cursor:
            yield f"    unsigned char pad_{cursor:04X}[{offset - cursor}];"
        yield _declaration(ranked[0], matched)
        for f in ranked[1:]:
            yield f"    /* {_offset(offset)}: also {_n(f.width, 'byte')} ({_notes(f, matched)}) */"
        cursor = offset + ranked[0].width


def _struct(shape: Shape, matched: frozenset[int]) -> str:
    bases = ", ".join(base.label() for base in shape.bases)
    head = f"/* {shape.name}: {_counted(shape.functions, matched)}; bases: {bases} */"
    return "\n".join([head, f"struct {shape.name} {{", *_layout(shape.fields, matched), "};"])


def header(shapes: Shapes, *, matched: frozenset[int]) -> str:
    """structs.h: every shape as a C89 struct, its members commented with their evidence.
    `matched` holds the starts of the matched rows (status.csv)."""
    guard = f"REVERSEAPOC_STRUCTS_{shapes.exe.upper()}_H"
    intro = (f"/* Struct shapes of {shapes.exe}, inferred by `reverseapoc structs {shapes.exe}` "
             f"from the field\n   accesses of {shapes.rows} rows of the original code. Generated "
             "reference data under build/:\n   never included by a matched unit and never "
             "committed; regenerate it, do not edit it.\n   Each member says how it is read and "
             "how many functions read or write it. */")  # fmt: skip
    parts = [intro, f"#ifndef {guard}\n#define {guard}"]
    parts += [_struct(shape, matched) for shape in shapes.shapes]
    parts.append(f"#endif /* {guard} */")
    return "\n\n".join(parts) + "\n"


def summary(shapes: Shapes, matched: frozenset[int]) -> str:
    """The verb's report: the counts, then one line per shape."""
    lines = [
        f"{shapes.exe}: {shapes.rows} rows read, {shapes.skipped} skipped; "
        f"{_n(shapes.bases, 'base pointer')} seen; {_n(shapes.links, 'link')} merged, "
        f"{shapes.refused} refused",
        f"{_n(len(shapes.shapes), 'struct shape')} of at least {MIN_FIELDS} fields",
    ]
    lines += [f"- {shape.name}: {_n(len(shape.fields), 'field')}, "
              f"{_counted(shape.functions, matched)}" for shape in shapes.shapes]  # fmt: skip
    return "\n".join(lines)


