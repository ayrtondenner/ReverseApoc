def matched_starts(config: Path, stem: str) -> frozenset[int]:
    """The starts of the rows config/<exe>/status.csv marks matched."""
    return frozenset(row.start for row in read_status(status_path(config, stem))
                     if row.status == MATCHED)  # fmt: skip


def shapes_dir(repo: Path, stem: str) -> Path:
    return Path(repo).joinpath(*SHAPES_PARTS, stem)


def shapes_path(repo: Path, stem: str) -> Path:
    """build/structs/<exe>/structs.json: what the context pack reads."""
    return shapes_dir(repo, stem) / DATA_FILE


def to_json(shapes: Shapes) -> dict[str, Any]:
    return {
        "format": FORMAT, "exe": shapes.exe, "rows": shapes.rows, "skipped": shapes.skipped,
        "bases": shapes.bases, "links": shapes.links, "refused": shapes.refused,
        "shapes": [{"name": shape.name,
                    "bases": [[base.kind, base.va, base.index] for base in shape.bases],
                    "fields": [[f.offset, f.width, f.sign, list(f.strides), list(f.functions)]
                               for f in shape.fields]}
                   for shape in shapes.shapes],
    }  # fmt: skip


def _typed(value: Any, kind: type) -> Any:
    if not isinstance(value, kind) or (kind is int and isinstance(value, bool)):
        raise TypeError(f"{value!r} is not {kind.__name__}")
    return value


def _ints(values: Any) -> tuple[int, ...]:
    return tuple(_typed(value, int) for value in _typed(values, list))


def _base(item: Any) -> Base:
    kind, va, index = _typed(item, list)
    if kind not in KINDS:
        raise ValueError(f"unknown base kind {kind!r}")
    return Base(kind, _typed(va, int), _typed(index, int))


def _field(item: Any) -> Field:
    offset, width, sign, strides, functions = _typed(item, list)
    return Field(_typed(offset, int), _typed(width, int), _typed(sign, str), _ints(strides),
                 _ints(functions))  # fmt: skip


def _shape(item: Any) -> Shape:
    item = _typed(item, dict)
    return Shape(_typed(item["name"], str), tuple(_base(b) for b in _typed(item["bases"], list)),
                 tuple(_field(f) for f in _typed(item["fields"], list)))  # fmt: skip


def from_json(data: Any) -> Shapes:
    data = _typed(data, dict)
    if data["format"] != FORMAT:
        raise ValueError(f"format {data['format']!r}, expected {FORMAT}")
    counts = (_typed(data[key], int) for key in ("rows", "skipped", "bases", "links", "refused"))
    return Shapes(_typed(data["exe"], str),
                  tuple(_shape(s) for s in _typed(data["shapes"], list)), *counts)  # fmt: skip


def load(repo: Path, stem: str) -> Shapes | None:
    """The shapes `write` left for `stem`, or None when there are none on this machine;
    StructsError, naming the file, when it is not structs.json of FORMAT."""
    path = shapes_path(repo, stem)
    if not path.is_file():
        return None
    try:
        return from_json(json.loads(path.read_text(encoding="utf-8")))
    except (ValueError, KeyError, TypeError) as exc:
        raise StructsError(f"{path}: not a {DATA_FILE} of format {FORMAT}: {exc}") from exc


def write(shapes: Shapes, matched: frozenset[int], *, repo: Path) -> tuple[Path, Path]:
    """Write structs.h and structs.json under build/structs/<exe>/ of `repo`; their paths."""
    directory = shapes_dir(repo, shapes.exe)
    directory.mkdir(parents=True, exist_ok=True)
    header_path, data_path = directory / HEADER_FILE, directory / DATA_FILE
    write_atomic(header_path, header(shapes, matched=matched).encode("utf-8"))
    text = json.dumps(to_json(shapes), indent=1, sort_keys=True) + "\n"
    write_atomic(data_path, text.encode("utf-8"))
    return header_path, data_path
