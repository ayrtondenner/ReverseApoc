"""Struct shapes inferred once across functions (todo struct-shapes-across-functions; research
notes docs/research/notes-ideas-llm-decomp-research.md #7).

Every game and thunk row of an EXE is read through the converter's own front end (lift.Lifter:
its decoding, filler removal, basic blocks and signatures), and a forward pass over its blocks
tracks which registers hold a base pointer, at what offset from it:

- a register argument (`arg`): eax, edx, ebx, ecx at entry, as many as the row's signature
  takes;
- a callee's result (`result`): eax after a direct call to a game or thunk row;
- the value of a global pointer (`pointer`): a dword load from a fixed-up address, `[D_x]`;
- the address of a global object (`object`): `mov r, offset D_x`, or `lea r, [D_x]`.

`mov r, r'` copies a base, `lea r, [b + d]` and `add`/`sub r, imm` move its offset, any other
write ends it, and a call keeps every register but eax (lift's `_use_def`). At a block join a
register keeps its base only when every predecessor agrees. Each memory operand on a held
register, `[b + d]` or `[b + i*s + d]`, is a field access: its offset, its width (the operand
size), how it is read (`s` movsx or an x87 integer, `u` movzx, `f` x87 real) and the index
scale. A displacement with a fixup is an address (a global array indexed by the register), and
string moves read their operands only implicitly, so neither is a field access.

Bases are joined across functions: a held base passed in argument register k (with offset 0)
to a game or thunk row whose signature takes more than k registers joins that callee's `arg k`,
and a base in eax at the `ret` of a row whose signature returns joins its `result`. A join is
refused when the two classes read one offset only at different widths (a polymorphic helper
such as a free list would otherwise merge unrelated structs). A class read at two offsets or
more is a struct shape.

`write` puts a C89 header (structs.h, reference data for packs and readability sessions, never
included by a matched unit) and its data (structs.json, what the context pack reads) under the
gitignored build/structs/<exe>/: both are derived from the game, like listings and packs, and
regenerated by `reverseapoc structs EXE`. include/ and src/ are never touched, so no matched
byte can move.
"""

