class MechanicsError(ValueError):
    """config/mechanics.toml or a mechanics CSV is malformed, or a generation input is wrong."""


SCHEMA = 1
EXES = ("ufo2p", "tacp")  # config/<exe> stems, in row order
MECHANICS_TOML = "mechanics.toml"
EVIDENCE_KINDS = ("file", "table", "string", "bios-tick", "call-graph", "data-field", "hand")
SCOPES = ("in", "out", "duplicate")
SCOPE_IN, SCOPE_OUT, SCOPE_DUPLICATE = SCOPES
TEXT_MAX = 120  # titles, details, reasons, sources: a short line in our own words
URL_MAX = 200
SIGNER_MAX = 64
HEX_RUN_MAX = 64  # a longer hex run could be game bytes (T-07-29); a SHA-256 is exactly 64

MEMBERS_CSV = "mechanics-members.csv"
MEMBERS_COMMENT = "# generated by: uv run reverseapoc mechanics write; do not edit"
MEMBERS_COLUMNS = ("exe", "address", "items", "tiers", "member_items", "via", "role")
ROLES = ("member", "hub", "closure", "asm")
ROLE_MEMBER, ROLE_HUB, ROLE_CLOSURE, ROLE_ASM = ROLES
VIAS = (ENTRY, *EDGE_KINDS)
WALKED_KINDS = (KIND_GAME, KIND_THUNK)  # the rows that can be members (D-02)

_ADDRESS = re.compile(r"0x[0-9A-F]{8}")
_ITEM_ID = re.compile(r"([1-9][0-9]*)(?:-([1-9][0-9]*))?")
_SHA256 = re.compile(r"[0-9a-f]{64}")
_HEX_RUN = re.compile(rf"[0-9A-Fa-f]{{{HEX_RUN_MAX + 1},}}")
_PRINTABLE = re.compile(r"[ -~]*")
_URL = re.compile(r"https://[!-~]+")
_LIST = ";"


# ---- the data model ----


@dataclass(frozen=True)
class AsmSignoff:
    """`[asm_list]`: the owner's sign-off of config/asm-functions.csv (D-23)."""

    signed_off_by: str = ""
    signed_off_date: datetime.date | None = None
    list_sha256: str = ""

    @property
    def signed(self) -> bool:
        return bool(self.signed_off_by)


@dataclass(frozen=True)
class HubRule:
    """`[hub_rule]` (D-22); 0 / false switches a criterion off."""

    min_direct_callers: int = 0
    largest_scc: bool = False
    max_closure_share: float = 0.0
    min_items: int = 0

    @property
    def enabled(self) -> bool:
        return bool(self.min_direct_callers or self.largest_scc or self.max_closure_share
                    or self.min_items)  # fmt: skip

    def line(self) -> str:
        """The canonical text of the rule, the first line of every tier digest."""
        return (f"hub_rule,min_direct_callers={self.min_direct_callers},"
                f"largest_scc={str(self.largest_scc).lower()},"
                f"max_closure_share={float(self.max_closure_share)!r},"
                f"min_items={self.min_items}")  # fmt: skip


@dataclass(frozen=True)
class Tier:
    id: int
    title: str
    signed_off_by: str = ""
    signed_off_date: datetime.date | None = None
    members_sha256: str = ""

    @property
    def signed(self) -> bool:
        return bool(self.signed_off_by)


@dataclass(frozen=True)
class Item:
    id: str
    issue: int
    title: str
    url: str
    tier: int
    scope: str
    duplicate_of: str = ""
    reason: str = ""
    exes: tuple[str, ...] = ()


@dataclass(frozen=True)
class Entry:
    item: str
    exe: str
    address: int
    evidence: str
    detail: str
    source: str = ""


@dataclass(frozen=True)
class HandEdge:
    exe: str
    src: int
    dst: int
    evidence: str


@dataclass(frozen=True)
class Mechanics:
    schema: int = SCHEMA
    asm_list: AsmSignoff = AsmSignoff()
    hub_rule: HubRule = HubRule()
    tiers: tuple[Tier, ...] = ()
    items: tuple[Item, ...] = ()
    entries: tuple[Entry, ...] = ()
    edges: tuple[HandEdge, ...] = ()

    def item(self, item_id: str) -> Item | None:
        return next((i for i in self.items if i.id == item_id), None)

    def tier(self, tier_id: int) -> Tier | None:
        return next((t for t in self.tiers if t.id == tier_id), None)

    def entry_addresses(self, item_id: str, exe: str) -> list[int]:
        return sorted({e.address for e in self.entries if e.item == item_id and e.exe == exe})

    def is_entry(self, exe: str, address: int) -> bool:
        """True when some [[entry]] names `address` in `exe`."""
        return any(e.exe == exe and e.address == address for e in self.entries)


def item_key(item_id: str) -> tuple[int, int]:
    """Sort key of an item id: (issue, number); the issue itself ("997") is number 0."""
    match = _ITEM_ID.fullmatch(item_id)
    if match is None:
        raise MechanicsError(f"item id {item_id!r} is not <issue> or <issue>-<n>")
    return int(match.group(1)), int(match.group(2) or 0)


# ---- the strict loader ----

_TOP_KEYS = ("schema", "asm_list", "hub_rule", "tier", "item", "entry", "edge")
_ASM_KEYS = ("signed_off_by", "signed_off_date", "list_sha256")
_HUB_KEYS = ("min_direct_callers", "largest_scc", "max_closure_share", "min_items")
_TIER_KEYS = ("id", "title", "signed_off_by", "signed_off_date", "members_sha256")
_ITEM_KEYS = ("id", "issue", "title", "url", "tier", "scope", "duplicate_of", "reason", "exes")
_ENTRY_KEYS = ("item", "exe", "address", "evidence", "detail", "source")
_EDGE_KEYS = ("exe", "from", "to", "evidence")


def _fail(where: str, key: str, problem: str) -> MechanicsError:
    return MechanicsError(f"{where}: key {key!r}: {problem}")


def _keys(where: str, body: Mapping, allowed: Sequence[str], required: Sequence[str]) -> None:
    for key in body:
        if key not in allowed:
            raise _fail(where, key, f"unknown key (allowed: {', '.join(allowed)})")
    for key in required:
        if key not in body:
            raise _fail(where, key, "missing")


def _int(where: str, body: Mapping, key: str, *, minimum: int = 0, default: int = 0) -> int:
    value = body.get(key, default)
    if isinstance(value, bool) or not isinstance(value, int):
        raise _fail(where, key, f"{value!r} is not an integer")
    if value < minimum:
        raise _fail(where, key, f"{value} is below {minimum}")
    return value


def _bool(where: str, body: Mapping, key: str) -> bool:
    value = body.get(key, False)
    if not isinstance(value, bool):
        raise _fail(where, key, f"{value!r} is not true or false")
    return value


def _share(where: str, body: Mapping, key: str) -> float:
    value = body.get(key, 0.0)
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not 0 <= value <= 1:
        raise _fail(where, key, f"{value!r} is not a share between 0 and 1")
    return float(value)


def _check_text(where: str, key: str, value: object, limit: int) -> str:
    if not isinstance(value, str):
        raise _fail(where, key, f"{value!r} is not a string")
    if not _PRINTABLE.fullmatch(value):
        raise _fail(where, key, "holds a character outside printable ASCII")
    if len(value) > limit:
        raise _fail(where, key, f"is {len(value)} characters long (at most {limit})")
    if _HEX_RUN.search(value):
        raise _fail(where, key, f"holds a hex run longer than {HEX_RUN_MAX} characters")
    return value


def _text(where: str, body: Mapping, key: str, *, limit: int = TEXT_MAX,
          required: bool = False) -> str:  # fmt: skip
    if key not in body:
        if required:
            raise _fail(where, key, "missing")
        return ""
    value = _check_text(where, key, body[key], limit)
    if required and not value.strip():
        raise _fail(where, key, "is empty")
    return value


def _choice(where: str, body: Mapping, key: str, allowed: Sequence[str]) -> str:
    value = body.get(key)
    if value not in allowed:
        raise _fail(where, key, f"{value!r} is not one of {', '.join(allowed)}")
    return value


def _address_value(where: str, body: Mapping, key: str) -> int:
    value = body.get(key)
    if not isinstance(value, str) or not _ADDRESS.fullmatch(value):
        raise _fail(where, key, f"{value!r} is not an address written 0x%08X")
    return int(value, 16)


def _date(where: str, body: Mapping, key: str) -> datetime.date:
    value = body[key]
    if not isinstance(value, datetime.date) or isinstance(value, datetime.datetime):
        raise _fail(where, key, f"{value!r} is not a TOML local date (YYYY-MM-DD)")
    return value


def _signoff(where: str, body: Mapping, digest_key: str) -> tuple[str, datetime.date | None, str]:
    """(who, date, digest): all three present or none (a partial sign-off is refused, T-07-30)."""
    keys = ("signed_off_by", "signed_off_date", digest_key)
    present = [key for key in keys if key in body]
    if not present:
        return "", None, ""
    if len(present) != len(keys):
        missing = ", ".join(key for key in keys if key not in body)
        problem = (f"a partial sign-off: signed_off_by, signed_off_date and {digest_key} come "
                   f"together ({missing} missing)")  # fmt: skip
        raise _fail(where, present[0], problem)
    who = _text(where, body, "signed_off_by", limit=SIGNER_MAX, required=True)
    digest = body[digest_key]
    if not isinstance(digest, str) or not _SHA256.fullmatch(digest):
        raise _fail(where, digest_key, "is not 64 lower-case hex digits (a SHA-256)")
    return who, _date(where, body, "signed_off_date"), digest


def _table(data: Mapping, key: str) -> Mapping:
    body = data.get(key, {})
    if not isinstance(body, dict):
        raise _fail("top level", key, f"must be a table ([{key}])")
    return body


def _array(data: Mapping, key: str) -> list[Mapping]:
    entries = data.get(key, [])
    if not isinstance(entries, list) or not all(isinstance(e, dict) for e in entries):
        raise _fail("top level", key, f"must be an array of tables ([[{key}]])")
    return entries


def _parse_asm(body: Mapping) -> AsmSignoff:
    _keys("asm_list", body, _ASM_KEYS, ())
    who, date, digest = _signoff("asm_list", body, "list_sha256")
    return AsmSignoff(who, date, digest)


def _parse_hub_rule(body: Mapping) -> HubRule:
    where = "hub_rule"
    _keys(where, body, _HUB_KEYS, ())
    return HubRule(
        min_direct_callers=_int(where, body, "min_direct_callers"),
        largest_scc=_bool(where, body, "largest_scc"),
        max_closure_share=_share(where, body, "max_closure_share"),
        min_items=_int(where, body, "min_items"),
    )


def _parse_tier(i: int, body: Mapping) -> Tier:
    where = f"tier[{i}]"
    _keys(where, body, _TIER_KEYS, ("id", "title"))
    who, date, digest = _signoff(where, body, "members_sha256")
    return Tier(_int(where, body, "id", minimum=1), _text(where, body, "title", required=True),
                who, date, digest)  # fmt: skip


def _parse_exes(where: str, body: Mapping, required: bool) -> tuple[str, ...]:
    if "exes" not in body:
        if required:
            raise _fail(where, "exes", "missing (an `in` item lists its EXEs)")
        return ()
    value = body["exes"]
    if (not isinstance(value, list) or not value or len(set(value)) != len(value)
            or any(exe not in EXES for exe in value)):  # fmt: skip
        raise _fail(where, "exes", f"{value!r} is not a list of distinct EXEs from "
                                   f"{', '.join(EXES)}")  # fmt: skip
    return tuple(sorted(value, key=EXES.index))


def _parse_item(i: int, body: Mapping) -> Item:
    where = f"item[{i}] ({body.get('id', '?')})"
    _keys(where, body, _ITEM_KEYS, ("id", "issue", "title", "tier", "scope"))
    item_id = _text(where, body, "id", limit=16, required=True)
    issue = _int(where, body, "issue", minimum=1)
    match = _ITEM_ID.fullmatch(item_id)
    if match is None or int(match.group(1)) != issue:
        raise _fail(where, "id", f"{item_id!r} is not <issue> or <issue>-<n> for issue {issue}")
    scope = _choice(where, body, "scope", SCOPES)
    url = _text(where, body, "url", limit=URL_MAX)
    if url and not _URL.fullmatch(url):
        raise _fail(where, "url", f"{url!r} is not an https:// URL")
    if scope != SCOPE_DUPLICATE and "duplicate_of" in body:
        raise _fail(where, "duplicate_of", "only a `duplicate` item names duplicate_of")
    duplicate_of = _text(where, body, "duplicate_of", limit=16,
                         required=scope == SCOPE_DUPLICATE)  # fmt: skip
    reason = _text(where, body, "reason", required=scope == SCOPE_OUT)
    return Item(item_id, issue, _text(where, body, "title", required=True), url,
                _int(where, body, "tier", minimum=1), scope, duplicate_of, reason,
                _parse_exes(where, body, required=scope == SCOPE_IN))  # fmt: skip


def _parse_entry(i: int, body: Mapping) -> Entry:
    where = f"entry[{i}]"
    _keys(where, body, _ENTRY_KEYS, ("item", "exe", "address", "evidence", "detail"))
    return Entry(
        item=_text(where, body, "item", limit=16, required=True),
        exe=_choice(where, body, "exe", EXES),
        address=_address_value(where, body, "address"),
        evidence=_choice(where, body, "evidence", EVIDENCE_KINDS),
        detail=_text(where, body, "detail", required=True),
        source=_text(where, body, "source"),
    )


def _parse_edge(i: int, body: Mapping) -> HandEdge:
    where = f"edge[{i}]"
    _keys(where, body, _EDGE_KEYS, _EDGE_KEYS)
    edge = HandEdge(_choice(where, body, "exe", EXES), _address_value(where, body, "from"),
                    _address_value(where, body, "to"),
                    _text(where, body, "evidence", required=True))  # fmt: skip
    if edge.src == edge.dst:
        raise _fail(where, "to", "a hand edge from a function to itself")
    return edge


def _unique(where: str, key: str, values: Iterable) -> None:
    seen = set()
    for value in values:
        if value in seen:
            raise _fail(where, key, f"{value!r} appears twice")
        seen.add(value)


def _check_items(mech: Mechanics) -> None:
    _unique("tier", "id", (t.id for t in mech.tiers))
    _unique("item", "id", (i.id for i in mech.items))
    for i, item in enumerate(mech.items):
        where = f"item[{i}] ({item.id})"
        if mech.tier(item.tier) is None:
            raise _fail(where, "tier", f"{item.tier} is not a [[tier]] id")
        if item.scope != SCOPE_DUPLICATE:
            continue
        target = mech.item(item.duplicate_of)
        if target is None or target.scope != SCOPE_IN:
            raise _fail(where, "duplicate_of", f"{item.duplicate_of!r} is not an `in` item")


def _check_entries(mech: Mechanics) -> None:
    _unique("entry", "address", ((e.item, e.exe, e.address) for e in mech.entries))
    for i, entry in enumerate(mech.entries):
        where = f"entry[{i}]"
        item = mech.item(entry.item)
        if item is None or item.scope != SCOPE_IN:
            raise _fail(where, "item", f"{entry.item!r} is not an `in` item")
        if entry.exe not in item.exes:
            raise _fail(where, "exe", f"{entry.exe} is not one of item {item.id}'s exes")
    _unique("edge", "to", ((e.exe, e.src, e.dst) for e in mech.edges))


def _parse(data: Mapping) -> Mechanics:
    _keys("top level", data, _TOP_KEYS, ("schema",))
    schema = data["schema"]
    if isinstance(schema, bool) or schema != SCHEMA:
        raise _fail("top level", "schema", f"{schema!r} is not {SCHEMA}")
    mech = Mechanics(
        schema=SCHEMA,
        asm_list=_parse_asm(_table(data, "asm_list")),
        hub_rule=_parse_hub_rule(_table(data, "hub_rule")),
        tiers=tuple(_parse_tier(i, b) for i, b in enumerate(_array(data, "tier"))),
        items=tuple(_parse_item(i, b) for i, b in enumerate(_array(data, "item"))),
        entries=tuple(_parse_entry(i, b) for i, b in enumerate(_array(data, "entry"))),
        edges=tuple(_parse_edge(i, b) for i, b in enumerate(_array(data, "edge"))),
    )
    _check_items(mech)
    _check_entries(mech)
    return mech


def load(path: Path) -> Mechanics:
    """Read and validate config/mechanics.toml; MechanicsError names the file, table and key. A
    missing file stays an OSError."""
    path = Path(path)
    with path.open("rb") as fh:
        try:
            data = tomllib.load(fh)
        except (tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
            raise MechanicsError(f"{path}: {exc}") from exc
    try:
        return _parse(data)
    except MechanicsError as exc:
        raise MechanicsError(f"{path}: {exc}") from exc


# ---- the members file ----


@dataclass(frozen=True)
class MemberRow:
    exe: str
    address: int
    items: tuple[str, ...]  # every item whose full closure reaches the row (D-02)
    tiers: tuple[int, ...]  # the tiers of `items`
    member_items: tuple[str, ...]  # the items whose hub-stopped closure has it as a member
    via: str  # the weakest edge kind on a shortest path from any entry
    role: str


def row_key(row: MemberRow) -> tuple[int, int]:
    return EXES.index(row.exe), row.address


def _cells(row: MemberRow) -> list[str]:
    return [row.exe, _address(row.address), _LIST.join(row.items),
            _LIST.join(str(t) for t in row.tiers), _LIST.join(row.member_items), row.via,
            row.role]  # fmt: skip


def format_members_csv(rows: Iterable[MemberRow]) -> str:
    """The members file text: comment, header, rows by (EXES order, address), LF."""
    ordered = sorted(rows, key=row_key)
    return _format_csv(MEMBERS_COMMENT, MEMBERS_COLUMNS, [_cells(row) for row in ordered])


def write_members(path: Path, rows: Iterable[MemberRow]) -> None:
    """Write the members file atomically (fileio.write_atomic)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    write_atomic(path, format_members_csv(rows).encode("ascii"))


def _id_list(cell: str, column: str) -> tuple[str, ...]:
    ids = tuple(cell.split(_LIST)) if cell else ()
    for item_id in ids:
        item_key(item_id)
    if list(ids) != sorted(set(ids), key=item_key):
        raise ValueError(f"{column} {cell!r} is not sorted by (issue, number) without repeats")
    return ids


def _parse_member(record: Mapping[str, str]) -> MemberRow:
    if None in record:
        raise ValueError("more fields than the header")
    exe, via, role = record["exe"], record["via"], record["role"]
    if exe not in EXES:
        raise ValueError(f"exe {exe!r} is not one of {', '.join(EXES)}")
    if not _ADDRESS.fullmatch(record["address"] or ""):
        raise ValueError(f"address {record['address']!r} is not written 0x%08X")
    items = _id_list(record["items"], "items")
    members = _id_list(record["member_items"], "member_items")
    if not items or not set(members) <= set(items):
        raise ValueError("items is empty or does not hold every member item")
    tiers = tuple(int(t) for t in record["tiers"].split(_LIST)) if record["tiers"] else ()
    if not tiers or list(tiers) != sorted(set(tiers)):
        raise ValueError(f"tiers {record['tiers']!r} is not a sorted list of tier ids")
    if via not in VIAS or role not in ROLES:
        raise ValueError(f"via {via!r} or role {role!r} is not a known value")
    if (role == ROLE_MEMBER) != bool(members):
        raise ValueError(f"role {role} does not agree with member_items {record['member_items']!r}")
    return MemberRow(exe, int(record["address"], 16), items, tiers, members, via, role)


def read_members(path: Path) -> list[MemberRow]:
    """The rows of a members file, validated. The file must be exactly what write_members writes
    for those rows (LF, comment, header, order, spelling), so a hand edit is refused."""
    path = Path(path)
    data = path.read_bytes()
    try:
        records = _read_records(path, MEMBERS_COLUMNS)
    except FunctionsError as exc:
        raise MechanicsError(str(exc)) from exc
    rows = []
    for number, record in enumerate(records, start=1):
        try:
            rows.append(_parse_member(record))
        except (TypeError, ValueError) as exc:
            raise MechanicsError(f"{path}: data row {number}: {exc}") from exc
    keys = [row_key(row) for row in rows]
    if keys != sorted(set(keys)) or data != format_members_csv(rows).encode("ascii"):
        raise MechanicsError(f"{path}: not written the way `mechanics write` writes it "
                             "(order, repeats, line endings or spelling)")  # fmt: skip
    return rows


# ---- the generator ----


def _walked(rows: Sequence[FunctionRow]) -> frozenset[int]:
    return frozenset(row.start for row in rows if row.kind in WALKED_KINDS)


# ---- hubs (D-22) ----


class HubStats:
    """The numbers the hub rule reads, for one EXE's graph: direct callers per row, the largest
    strongly connected component over all edge kinds, each row's own closure share (computed when
    asked) and how many `in` items' full closures reach each row."""

    def __init__(self, graph: CallGraph, walked: frozenset[int],
                 closures: Mapping[str, frozenset[int]]) -> None:  # fmt: skip
        self.graph, self.walked = graph, walked
        self.direct_callers = Counter(edge.dst for edges in graph.edges.values()
                                      for edge in edges if edge.kind == DIRECT)  # fmt: skip
        self.item_counts = Counter(node for nodes in closures.values() for node in nodes)
        self._sizes: dict[int, int] = {}

    @cached_property
    def largest_scc(self) -> frozenset[int]:
        """The largest cycle (ties: the first in callgraph.sccs order); empty without a cycle."""
        cycles = [comp for comp in callgraph.sccs(self.graph, self.walked) if len(comp) > 1]
        return max(cycles, key=len, default=frozenset())

    def closure_share(self, start: int) -> float:
        """The share of the EXE's game/thunk rows that `start` reaches (itself included)."""
        if start not in self._sizes:
            self._sizes[start] = len(callgraph.closure(self.graph, [start]) & self.walked)
        return self._sizes[start] / max(len(self.walked), 1)


def hub_stats(graph: CallGraph, walked: frozenset[int],
              closures: Mapping[str, frozenset[int]]) -> HubStats:  # fmt: skip
    return HubStats(graph, walked, closures)


def is_hub(start: int, rule: HubRule, graph: CallGraph, stats: HubStats) -> bool:
    """True when `start` meets any enabled criterion of the hub rule (D-22): at least
    min_direct_callers direct callers, in the largest SCC, an own closure above
    max_closure_share of the EXE, or reached by at least min_items `in` items."""
    if stats.graph is not graph:
        raise MechanicsError("hub stats were computed for another graph")
    return bool(
        (rule.min_direct_callers and stats.direct_callers[start] >= rule.min_direct_callers)
        or (rule.largest_scc and start in stats.largest_scc)
        or (rule.max_closure_share and stats.closure_share(start) > rule.max_closure_share)
        or (rule.min_items and stats.item_counts[start] >= rule.min_items)
    )


# ---- the walk ----


@dataclass
class _ExeWalk:
    """One EXE's full closures (D-02), hub-stopped member sets (D-22, D-31), hubs, asm rows and
    the via of every reached row."""

    exe: str
    full: dict[str, frozenset[int]]  # item id -> full closure
    members: dict[str, frozenset[int]]  # item id -> must-match members
    hubs: frozenset[int]
    asm: frozenset[int]
    via: dict[int, str]


def _roots(mech: Mechanics, exe: str, walked: frozenset[int]) -> dict[str, list[int]]:
    """The `in` items with entries in `exe`, mapped to their entry addresses."""
    roots = {}
    for item in mech.items:
        addresses = mech.entry_addresses(item.id, exe) if item.scope == SCOPE_IN else []
        stray = [a for a in addresses if a not in walked]
        if stray:
            raise MechanicsError(f"item {item.id}: entry {_address(stray[0])} is not a game or "
                                 f"thunk row of config/{exe}/functions.csv")  # fmt: skip
        if addresses:
            roots[item.id] = addresses
    return roots


def _with_hand_edges(mech: Mechanics, exe: str, graph: CallGraph,
                     walked: frozenset[int]) -> CallGraph:  # fmt: skip
    """`graph` plus this EXE's `[[edge]]` entries as `hand` edges (game/thunk rows only)."""
    extra = []
    for edge in (e for e in mech.edges if e.exe == exe):
        if edge.src not in walked or edge.dst not in walked:
            raise MechanicsError(f"edge {_address(edge.src)} -> {_address(edge.dst)} in {exe}: "
                                 "both ends must be game or thunk rows")  # fmt: skip
        extra.append(callgraph.Edge(edge.src, edge.dst, HAND))
    return callgraph.with_edges(graph, extra) if extra else graph


def _check_asm_entries(roots: Mapping[str, list[int]], exe: str, asm: frozenset[int]) -> None:
    for item_id, addresses in roots.items():
        if listed := asm.intersection(addresses):
            raise MechanicsError(f"item {item_id}: entry {_address(min(listed))} in {exe} is on "
                                 "the asm list (D-23): assembler cannot match from C")  # fmt: skip


def _walk_exe(mech: Mechanics, exe: str, graph: CallGraph, walked: frozenset[int],
              asm: frozenset[int]) -> _ExeWalk:  # fmt: skip
    graph = _with_hand_edges(mech, exe, graph, walked)
    roots = _roots(mech, exe, walked)
    _check_asm_entries(roots, exe, asm)
    full = {item_id: callgraph.closure(graph, addresses) & walked
            for item_id, addresses in roots.items()}  # fmt: skip
    reached = frozenset().union(*full.values())
    hubs: frozenset[int] = frozenset()
    if mech.hub_rule.enabled:
        stats = hub_stats(graph, walked, full)
        hubs = frozenset(n for n in reached if is_hub(n, mech.hub_rule, graph, stats))
    members = {}
    for item_id, addresses in roots.items():
        stop = (hubs | asm) - set(addresses)  # an item's entries are always its members (D-31)
        members[item_id] = (callgraph.closure(graph, addresses, stop=stop) & walked) - stop
    all_roots = sorted({a for addresses in roots.values() for a in addresses})
    via = {node: kind for node, (_hops, kind) in callgraph.reach(graph, all_roots).items()}
    return _ExeWalk(exe, full, members, hubs, asm & reached, via)


def _role(walk: _ExeWalk, node: int, members: tuple[str, ...]) -> str:
    if members:
        return ROLE_MEMBER
    if node in walk.asm:
        return ROLE_ASM
    return ROLE_HUB if node in walk.hubs else ROLE_CLOSURE


def _exe_rows(mech: Mechanics, walk: _ExeWalk) -> list[MemberRow]:
    tier_of = {item.id: item.tier for item in mech.items}
    reached = sorted(set().union(*walk.full.values())) if walk.full else []
    rows = []
    for node in reached:
        items = tuple(sorted((i for i, nodes in walk.full.items() if node in nodes), key=item_key))
        members = tuple(i for i in items if node in walk.members[i])
        rows.append(MemberRow(walk.exe, node, items, tuple(sorted({tier_of[i] for i in items})),
                              members, walk.via[node], _role(walk, node, members)))  # fmt: skip
    return rows


def compute_members(
    mech: Mechanics,
    graphs: Mapping[str, CallGraph],
    rows_by_exe: Mapping[str, Sequence[FunctionRow]],
    asm: Iterable[tuple[str, int]] = frozenset(),
) -> list[MemberRow]:
    """The members rows of every EXE with entries, sorted.

    `rows_by_exe` holds each EXE's functions.csv rows: only game and thunk rows appear (runtime
    rows are leaves, D-02). `asm` holds the (exe, address) pairs the signed asm list marks `asm`
    (D-23). Per `in` item: its full closure over every edge kind gives `items`/`tiers`; a walk
    from its entries that does not expand hubs (rows meeting the hub rule, D-22) or asm rows
    gives its members, the entries always included (D-31). A row's role is member when it is
    some item's member, else asm when listed, else hub when it meets the rule, else closure (it
    is reached only through hubs or asm rows). `[[edge]]` hand edges join the graph first."""
    pairs = frozenset(asm)
    rows: list[MemberRow] = []
    for exe in needed_exes(mech):
        if exe not in graphs or exe not in rows_by_exe:
            raise MechanicsError(f"no call graph or functions.csv rows for {exe}")
        rows += _exe_members(mech, exe, graphs[exe], rows_by_exe[exe], pairs)
    return sorted(rows, key=row_key)


def _exe_members(mech: Mechanics, exe: str, graph: CallGraph, rows: Sequence[FunctionRow],
                 asm: frozenset[tuple[str, int]]) -> list[MemberRow]:  # fmt: skip
    listed = frozenset(address for name, address in asm if name == exe)
    return _exe_rows(mech, _walk_exe(mech, exe, graph, _walked(rows), listed))


def needed_exes(mech: Mechanics) -> tuple[str, ...]:
    """The EXEs that hold an entry of an `in` item, in EXES order."""
    used = {e.exe for e in mech.entries}
    return tuple(exe for exe in EXES if exe in used)


def load_graphs(
    config_root: Path, orig_dir: Path, manifest: Path, exes: Sequence[str] = EXES
) -> dict[str, CallGraph]:
    """The call graphs of the user's own EXEs (needs orig/; the tests replace this seam)."""
    from .check import load_exe, select_exe  # check pulls in the compiler plumbing
    from .targets import load_manifest

    targets = load_manifest(manifest)
    graphs = {}
    for exe in exes:
        target = select_exe(targets, exe, manifest)
        inputs = load_exe(target, orig_dir=orig_dir, manifest=manifest, config_root=config_root)
        graphs[exe] = callgraph.build_for(inputs)
    return graphs


def read_rows(config_root: Path, exes: Iterable[str]) -> dict[str, list[FunctionRow]]:
    """config/<exe>/functions.csv of each EXE."""
    return {exe: read_functions_csv(Path(config_root) / exe / "functions.csv") for exe in exes}


def generate(config_root: Path, orig_dir: Path, manifest: Path) -> list[MemberRow]:
    """The members rows from config/mechanics.toml, functions.csv and the EXEs' call graphs. A
    file with no entries needs no game files."""
    config_root = Path(config_root)
    mech = load(config_root / MECHANICS_TOML)
    exes = needed_exes(mech)
    asm = signed_asm(config_root, mech)
    graphs = load_graphs(config_root, orig_dir, manifest, exes) if exes else {}
    return compute_members(mech, graphs, read_rows(config_root, exes), asm)



# ---- tier digests (D-04, T-07-28) ----


def _tier_role(row: MemberRow, tier_members: Sequence[str]) -> str:
    """The row's role as tier N sees it: member when a tier-N item has it as a member, else its
    asm/hub/closure class. A row that is a member only of another tier's item carries no class
    in the file: a hub is a member only as some item's entry (D-31), so such a row counts as hub
    when it is an entry (`via` entry) and as closure otherwise."""
    if tier_members:
        return ROLE_MEMBER
    if row.role != ROLE_MEMBER:
        return row.role
    return ROLE_HUB if row.via == ENTRY else ROLE_CLOSURE


def _toml_lines(mech: Mechanics, tier_id: int, reached: set[tuple[str, int]]) -> list[str]:
    """The signed TOML side of a tier digest: its items (every scope), their entries and the hand
    edges leaving its rows, each a JSON array (text fields escaped), in a fixed order."""
    items = sorted((i for i in mech.items if i.tier == tier_id), key=lambda i: item_key(i.id))
    ids = {item.id for item in items}
    entries = sorted((e for e in mech.entries if e.item in ids),
                     key=lambda e: (item_key(e.item), EXES.index(e.exe), e.address))  # fmt: skip
    edges = sorted((e for e in mech.edges if (e.exe, e.src) in reached),
                   key=lambda e: (EXES.index(e.exe), e.src, e.dst))  # fmt: skip
    lines = [["item", i.id, i.issue, i.title, i.url, i.scope, i.duplicate_of, i.reason,
              list(i.exes)] for i in items]  # fmt: skip
    lines += [["entry", e.item, e.exe, _address(e.address), e.evidence, e.detail, e.source]
              for e in entries]  # fmt: skip
    lines += [["edge", e.exe, _address(e.src), _address(e.dst), e.evidence] for e in edges]
    return [json.dumps(line, separators=(",", ":")) for line in lines]


def tier_digest(mech: Mechanics, rows: Iterable[MemberRow], tier_id: int) -> str:
    """SHA-256 (hex) of tier N's canonical projection, the record the owner signs (D-04, T-07-28):

    1. the hub-rule line (HubRule.line);
    2. one line `exe,address,<tier-N items>,<tier-N member items>,<tier-N role>` per members row a
       tier-N item reaches, by (EXES order, address);
    3. one JSON line per tier-N `[[item]]` of every scope (id, issue, title, url, scope,
       duplicate_of, reason, exes), by (issue, number);
    4. one JSON line per `[[entry]]` of those items (item, exe, address, evidence, detail,
       source), by (item, EXE, address);
    5. one JSON line per hand `[[edge]]` whose `from` row is a row of step 2 (exe, from, to,
       evidence), by (EXE, from, to).

    So any edit of the tier's signed TOML, or of its generated rows, reopens the sign-off. Adding
    a later tier's item leaves it unchanged, except through the min_items hub criterion (it
    counts items of every tier), a hand edge from one of its rows, or a later-tier entry that is
    not a hub and that tier N reaches only through hubs (see _tier_role); `mechanics check` then
    asks for a re-sign."""
    if mech.tier(tier_id) is None:
        raise MechanicsError(f"no [[tier]] with id {tier_id} in mechanics.toml")
    ids = {item.id for item in mech.items if item.tier == tier_id}
    lines = [mech.hub_rule.line()]
    reached: set[tuple[str, int]] = set()
    for row in sorted(rows, key=row_key):
        items = [i for i in row.items if i in ids]
        if not items:
            continue
        reached.add((row.exe, row.address))
        members = [i for i in row.member_items if i in ids]
        lines.append(",".join((row.exe, _address(row.address), _LIST.join(items),
                               _LIST.join(members), _tier_role(row, members))))  # fmt: skip
    lines += _toml_lines(mech, tier_id, reached)
    return hashlib.sha256(("\n".join(lines) + "\n").encode("ascii")).hexdigest()


def signed_tiers(mech: Mechanics, rows: Sequence[MemberRow]) -> tuple[int, ...]:
    """The ids of the tiers whose sign-off is present and whose digest still matches."""
    return tuple(sorted(tier.id for tier in mech.tiers
                        if tier.signed and tier.members_sha256 == tier_digest(mech, rows, tier.id)))


# ---- the asm list (D-23; written by `mechanics asm`, plan 07-12) ----

ASM_CSV = "asm-functions.csv"
ASM_COMMENT = (
    "# generated by: uv run reverseapoc mechanics asm --write; the tool owns exe, address and "
    "evidence; verdict and reason are written by hand where the owner overrides (D-23)"
)
ASM_COLUMNS = ("exe", "address", "evidence", "verdict", "reason")
ASM_VERDICTS = ("asm", "c", "unclear")
VERDICT_ASM = "asm"


@dataclass(frozen=True)
class AsmRow:
    exe: str
    address: int
    evidence: str
    verdict: str
    reason: str = ""


def _asm_key(row: AsmRow) -> tuple[int, int]:
    return EXES.index(row.exe), row.address


def format_asm_csv(rows: Iterable[AsmRow]) -> str:
    """The asm list text: comment, header, rows by (EXES order, address), LF."""
    cells = [[row.exe, _address(row.address), row.evidence, row.verdict, row.reason]
             for row in sorted(rows, key=_asm_key)]  # fmt: skip
    return _format_csv(ASM_COMMENT, ASM_COLUMNS, cells)


def _parse_asm_row(record: Mapping[str, str]) -> AsmRow:
    if None in record:
        raise ValueError("more fields than the header")
    where = "asm row"
    return AsmRow(
        exe=_choice(where, record, "exe", EXES),
        address=_address_value(where, record, "address"),
        evidence=_text(where, record, "evidence", required=True),
        verdict=_choice(where, record, "verdict", ASM_VERDICTS),
        reason=_text(where, record, "reason"),
    )


def read_asm_list(path: Path) -> list[AsmRow]:
    """The rows of config/asm-functions.csv, validated; the file must be exactly what
    format_asm_csv writes for them (CRLF read as LF)."""
    path = Path(path)
    try:
        records = _read_records(path, ASM_COLUMNS)
    except FunctionsError as exc:
        raise MechanicsError(str(exc)) from exc
    rows = []
    for number, record in enumerate(records, start=1):
        try:
            rows.append(_parse_asm_row(record))
        except (TypeError, ValueError) as exc:
            raise MechanicsError(f"{path}: data row {number}: {exc}") from exc
    keys = [_asm_key(row) for row in rows]
    text = path.read_bytes().replace(b"\r\n", b"\n")
    if keys != sorted(set(keys)) or text != format_asm_csv(rows).encode("utf-8"):
        raise MechanicsError(f"{path}: not written the way format_asm_csv writes it (comment, "
                             "order, repeats or spelling)")  # fmt: skip
    return rows


def asm_list_sha256(path: Path) -> str:
    """SHA-256 (hex) of the asm list's bytes with CRLF read as LF: the [asm_list] sign-off."""
    return hashlib.sha256(Path(path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def _asm_pairs(rows: Iterable[AsmRow]) -> frozenset[tuple[str, int]]:
    return frozenset((row.exe, row.address) for row in rows if row.verdict == VERDICT_ASM)


def _asm_signoff_problem(mech: Mechanics, path: Path) -> str:
    if not path.is_file():
        return f"[asm_list] is signed off but {path} is missing" if mech.asm_list.signed else ""
    if not mech.asm_list.signed:
        return f"{path} exists but [asm_list] in mechanics.toml is not signed off (D-23)"
    now = asm_list_sha256(path)
    if now != mech.asm_list.list_sha256:
        return (f"{path} changed since its sign-off (D-23): re-sign [asm_list] "
                f"(list_sha256 is now {now})")  # fmt: skip
    return ""


def signed_asm(config_root: Path, mech: Mechanics) -> frozenset[tuple[str, int]]:
    """The (exe, address) pairs the asm list marks `asm`. No list: none. A list that is not
    signed off in [asm_list], or changed since, is refused (D-23)."""
    path = Path(config_root) / ASM_CSV
    if not path.is_file():
        return frozenset()
    if problem := _asm_signoff_problem(mech, path):
        raise MechanicsError(problem)
    return _asm_pairs(read_asm_list(path))


# ---- the committed-data check (CI, no game files) ----


def _row_problems(mech: Mechanics, rows: Sequence[MemberRow], walked: Mapping[str, frozenset[int]],
                  asm: frozenset[tuple[str, int]]) -> Iterator[str]:  # fmt: skip
    for row in rows:
        where = f"{MEMBERS_CSV} {row.exe} {_address(row.address)}"
        if row.address not in walked[row.exe]:
            yield f"{where}: not a game or thunk row of config/{row.exe}/functions.csv"
        items = [mech.item(i) for i in row.items]
        if any(item is None or item.scope != SCOPE_IN for item in items):
            yield f"{where}: items {_LIST.join(row.items)} are not all `in` items"
        elif tuple(sorted({item.tier for item in items if item})) != row.tiers:
            yield f"{where}: tiers {_LIST.join(map(str, row.tiers))} do not match its items"
        if (row.role == ROLE_ASM) != ((row.exe, row.address) in asm):
            yield f"{where}: role {row.role} disagrees with the asm list"
        if row.via == ENTRY and not mech.is_entry(row.exe, row.address):
            yield f"{where}: via entry but no [[entry]] names it"


def _entry_problems(mech: Mechanics, rows: Sequence[MemberRow],
                    asm: frozenset[tuple[str, int]]) -> Iterator[str]:  # fmt: skip
    index = {(row.exe, row.address): row for row in rows}
    for entry in mech.entries:
        where = f"entry {entry.item} {entry.exe} {_address(entry.address)}"
        if (entry.exe, entry.address) in asm:
            yield f"{where}: on the asm list (D-23): assembler cannot match from C"
        row = index.get((entry.exe, entry.address))
        if row is None or row.via != ENTRY or entry.item not in row.member_items:
            yield (f"{where}: not in {MEMBERS_CSV} with via entry as a member of its item "
                   "(run `uv run reverseapoc mechanics write`)")  # fmt: skip


def _tier_problems(mech: Mechanics, rows: Sequence[MemberRow]) -> Iterator[str]:
    with_entries = {entry.item for entry in mech.entries}
    for tier in (t for t in mech.tiers if t.signed):
        bare = [i.id for i in mech.items
                if i.tier == tier.id and i.scope == SCOPE_IN and i.id not in with_entries]
        if bare:
            yield f"tier {tier.id} is signed off but `in` items {', '.join(bare)} have no entry"
        digest = tier_digest(mech, rows, tier.id)
        if digest != tier.members_sha256:
            yield (f"tier {tier.id} changed since sign-off: re-sign (members_sha256 is "
                   f"{tier.members_sha256}, the rows now give {digest})")  # fmt: skip


def check_committed(config_root: Path) -> list[str]:
    """Problems in the committed mechanics files (no game files needed): members rows that are
    not game/thunk rows of functions.csv, items that are not `in`, entries missing with via
    entry, signed tiers whose digest changed or that hold an entry-less `in` item, and an asm
    list that is unsigned, changed since its sign-off or lists an entry. No mechanics.toml:
    nothing to check. A malformed file raises MechanicsError (a tool error, not a problem)."""
    root = Path(config_root)
    if not (root / MECHANICS_TOML).is_file():
        return []
    mech = load(root / MECHANICS_TOML)
    asm_path = root / ASM_CSV
    problems = [p for p in [_asm_signoff_problem(mech, asm_path)] if p]
    asm = _asm_pairs(read_asm_list(asm_path)) if asm_path.is_file() else frozenset()
    members_path = root / MEMBERS_CSV
    rows: list[MemberRow] = []
    if members_path.is_file():
        rows = read_members(members_path)
    elif mech.entries:
        problems.append(f"{members_path} is missing: run `uv run reverseapoc mechanics write`")
    exes = sorted({row.exe for row in rows}, key=EXES.index)
    walked = {exe: _walked(found) for exe, found in read_rows(root, exes).items()}
    problems += _row_problems(mech, rows, walked, asm)
    problems += _entry_problems(mech, rows, asm)
    problems += _tier_problems(mech, rows)
    return problems


def read_committed(config_root: Path) -> tuple[Mechanics, list[MemberRow]]:
    """mechanics.toml and the members file (no rows when it is absent)."""
    root = Path(config_root)
    mech = load(root / MECHANICS_TOML)
    members_path = root / MEMBERS_CSV
    return mech, read_members(members_path) if members_path.is_file() else []


def _tier_ids(mech: Mechanics, tier_id: int) -> frozenset[str]:
    if mech.tier(tier_id) is None:
        raise MechanicsError(f"no [[tier]] with id {tier_id} in mechanics.toml")
    return frozenset(item.id for item in mech.items if item.tier == tier_id)


# ---- the done rule: tier status (D-05) ----


@dataclass(frozen=True)
class TierStatus:
    """A tier's must-match set (role member rows with a member item of the tier) against
    status.csv. `unmatched_starts` lists every member not yet matched (partial included)."""

    total: int
    matched: int
    partial: int
    unmatched: int
    unmatched_starts: tuple[tuple[str, int], ...] = ()


def tier_status(mech: Mechanics, rows: Iterable[MemberRow],
                statuses: Mapping[tuple[str, int], str], tier_id: int) -> TierStatus:  # fmt: skip
    """Matched/partial/unmatched counts of tier `tier_id`'s members; `statuses` maps (exe, start)
    to a status.csv status (no entry = unmatched)."""
    ids = _tier_ids(mech, tier_id)
    members = [row for row in sorted(rows, key=row_key)
               if row.role == ROLE_MEMBER and ids.intersection(row.member_items)]  # fmt: skip
    found = Counter(statuses.get((row.exe, row.address), "") for row in members)
    waiting = tuple((row.exe, row.address) for row in members
                    if statuses.get((row.exe, row.address)) != MATCHED)  # fmt: skip
    return TierStatus(len(members), found[MATCHED], found[PARTIAL],
                      len(members) - found[MATCHED] - found[PARTIAL], waiting)  # fmt: skip


def done_problems(mech: Mechanics, rows: Sequence[MemberRow],
                  found: Mapping[int, TierStatus]) -> list[str]:  # fmt: skip
    """Why the D-05 done rule does not hold for the tiers in `found` (empty: it holds). A tier is
    done only when it is signed off, its digest still matches (the comparison `mechanics check`
    makes), it has members and every member is matched. No tier at all is not done."""
    if not found:
        return ["no tier to check: mechanics.toml has no [[tier]]"]
    signed = signed_tiers(mech, rows)
    problems = []
    for tier_id, status in found.items():
        tier = mech.tier(tier_id)
        if tier is None or not tier.signed:
            problems.append(f"tier {tier_id} is not signed off")
        elif tier_id not in signed:
            problems.append(f"tier {tier_id} changed since sign-off: re-sign")
        if status.total == 0:
            problems.append(f"tier {tier_id} has no members (is {MEMBERS_CSV} written?)")
        elif status.matched != status.total:
            problems.append(f"tier {tier_id}: {status.total - status.matched} of "
                            f"{status.total} members not matched")  # fmt: skip
    return problems


def read_statuses(config_root: Path, exes: Iterable[str]) -> dict[tuple[str, int], str]:
    """(exe, start) -> status from each EXE's config/<exe>/status.csv (absent: none)."""
    return {(exe, row.start): row.status for exe in exes
            for row in read_status(status_path(Path(config_root), exe))}  # fmt: skip


# ---- graph reports and hub-rule candidates (D-22; plan 07-22 shows them to the owner) ----

DEFAULT_HUB_KS = (10, 20, 40, 80)
_RESEARCH_KINDS = (DIRECT, POINTER, TABLE)  # research Q1's edge set


def _only(graph: CallGraph, kinds: Sequence[str]) -> CallGraph:
    """`graph` with only the edges of `kinds` (the reports are not carried)."""
    return CallGraph(edges={start: tuple(e for e in edges if e.kind in kinds)
                            for start, edges in graph.edges.items()})  # fmt: skip


def _largest_component(graph: CallGraph, kinds: Sequence[str]) -> int:
    restricted = _only(graph, kinds)
    return max((len(comp) for comp in callgraph.sccs(restricted, restricted.edges)), default=0)


def graph_report(graph: CallGraph) -> dict:
    """Addresses and counts only: edges per kind, every mid-row reference, the unresolvable
    indirect calls per row, the orphan pointer runs and the largest SCC per edge set."""
    kinds = Counter(edge.kind for edges in graph.edges.values() for edge in edges)
    midrow = [{"source": _address(ref.src_va),
               "source_row": None if ref.src_row is None else _address(ref.src_row),
               "target": _address(ref.target_va), "target_row": _address(ref.target_row),
               "origin": ref.origin, "boundary": ref.boundary} for ref in graph.midrow]  # fmt: skip
    return {
        "edges": {kind: kinds[kind] for kind in EDGE_KINDS},
        "midrow": midrow,
        "indirect": [{"row": _address(start), "count": n}
                     for start, n in sorted(graph.indirect.items())],  # fmt: skip
        "orphan_tables": [_address(start) for start in graph.orphan_tables],
        "largest_scc": {"direct": _largest_component(graph, (DIRECT,)),
                        "direct_pointer_table": _largest_component(graph, _RESEARCH_KINDS),
                        "all": _largest_component(graph, EDGE_KINDS)},  # fmt: skip
    }


def _candidate(mech: Mechanics, exe: str, graph: CallGraph, rows: Sequence[FunctionRow],
               asm: frozenset[tuple[str, int]], tier_id: int, k: int) -> dict:  # fmt: skip
    trial = replace(mech, hub_rule=replace(mech.hub_rule, min_direct_callers=k))
    ids = _tier_ids(mech, tier_id)
    found = [r for r in _exe_members(trial, exe, graph, rows, asm) if ids.intersection(r.items)]
    direct = _exe_members(trial, exe, _only(graph, (DIRECT,)), rows, asm)
    must = [r for r in found if ids.intersection(r.member_items)]
    callers = Counter(e.dst for edges in graph.edges.values() for e in edges if e.kind == DIRECT)
    hubs = [r.address for r in found
            if _tier_role(r, [i for i in r.member_items if i in ids]) == ROLE_HUB]  # fmt: skip
    vias = Counter(r.via for r in must)
    return {
        "k": k,
        "must_match": len(must),
        "must_match_direct": sum(1 for r in direct if ids.intersection(r.member_items)),
        "hubs": [{"address": _address(a), "callers": callers[a]} for a in hubs],
        "members_by_via": {via: vias[via] for via in VIAS if vias[via]},
        "asm_removed": sum(1 for r in found if r.role == ROLE_ASM),
    }


def hub_candidates(mech: Mechanics, graphs: Mapping[str, CallGraph],
                   rows_by_exe: Mapping[str, Sequence[FunctionRow]],
                   asm: Iterable[tuple[str, int]], tier_id: int,
                   ks: Iterable[int] = DEFAULT_HUB_KS) -> dict:  # fmt: skip
    """The numbers for choosing the hub rule (D-22) for tier `tier_id`, per EXE and per K (the
    min_direct_callers value tried; the other [hub_rule] criteria stay as written): the tier's
    must-match count over all edges and over direct edges only (hand edges kept), the hubs with
    their direct caller counts, the members per `via` kind and the asm rows taken out."""
    pairs = frozenset(asm)
    _tier_ids(mech, tier_id)
    report: dict = {"tier": tier_id, "exes": {}}
    for exe in needed_exes(mech):
        report["exes"][exe] = [_candidate(mech, exe, graphs[exe], rows_by_exe[exe], pairs,
                                          tier_id, k) for k in sorted(set(ks))]  # fmt: skip
    return report
