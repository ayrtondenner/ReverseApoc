"""The DEC-01 mechanics map: which functions answer which OpenApoc checklist item (D-01, D-02,
D-04, D-22, D-23, D-31; research 07-R1 §Q5).

Two committed files:

- `config/mechanics.toml`, hand-edited: `schema = 1`, `[asm_list]` (the owner's sign-off of
  config/asm-functions.csv, D-23), `[hub_rule]` (D-22), `[[tier]]` (with its sign-off record),
  `[[item]]` (an OpenApoc checklist item, in/out/duplicate), `[[entry]]` (an item's entry
  function in one EXE, with its evidence) and `[[edge]]` (a `hand` call edge a reader proved).
  `load` refuses, naming the table and key, any unknown key, wrong type, unknown enum value,
  non-ASCII or overlong text, a hex run longer than HEX_RUN_MAX characters and a partial
  sign-off. Only addresses, ids and short evidence text in our own words: never function names,
  game strings or OpenApoc text (D-21).
- `config/mechanics-members.csv`, generated by `uv run reverseapoc mechanics write` from the
  TOML, functions.csv and the call graph of the user's own EXEs (callgraph.py), never edited:
  one row per game/thunk function reached by any `in` item's full closure (D-02), with the items
  and tiers that reach it, the items it is a must-match member of, `via` (the weakest edge kind
  on a shortest path from any entry) and its role.

Addresses are `0x%08X`; rows sort by EXE (EXES order) then address; ids sort by (issue, number).
"""

