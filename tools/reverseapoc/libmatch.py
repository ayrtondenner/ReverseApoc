def select_target(targets: Sequence[Target], exe: str, manifest: Path) -> Target:
    """The manifest target named `exe`, or whose stem is `exe` (case-insensitive). `exe` only
    selects among the manifest's names; it never becomes part of a path."""
    key = exe.casefold()
    for target in targets:
        if key in (target.name.casefold(), PurePosixPath(target.name).stem.casefold()):
            return target
    known = ", ".join(t.name for t in targets)
    raise LibMatchError(f"{manifest}: no target named {exe!r}; known targets: {known}")


def read_target(target: Target, orig_dir: Path, manifest: Path) -> bytes:
    """The bytes of orig_dir/<name>, read once and checked against the manifest (size, CRC32,
    MD5, SHA-1) before anything is parsed."""
    check_bare_name(target.name)
    source = Path(orig_dir) / target.name
    if not source.is_file():
        raise LibMatchError(f"{source} not found; run `uv run reverseapoc ingest`")
    data = source.read_bytes()
    if target_problems(target, hash_bytes(data)):
        raise LibMatchError(
            f"{source} does not match {manifest}; run `uv run reverseapoc check-orig`"
        )
    return data


def check_versions(versions: Sequence[str]) -> None:
    """Each version names one directory under the Watcom dir, never a path."""
    for version in versions:
        bare = PurePosixPath(version).name == version == PureWindowsPath(version).name
        if not version or not bare or version in (".", ".."):
            raise LibMatchError(f"version {version!r} must be a bare directory name")


def refuse_output(path: Path, *protected: Path) -> None:
    """Refuse an output path inside orig/ or the Watcom tree: both are only ever read."""
    resolved = Path(path).resolve()
    for directory in protected:
        if resolved.is_relative_to(Path(directory).resolve()):
            raise LibMatchError(f"refusing to write {path}: it lies inside {directory}")


