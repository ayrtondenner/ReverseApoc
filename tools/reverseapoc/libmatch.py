def _cells(r: MatchRange) -> list[str]:
    join = _LIST_SEPARATOR.join
    return [f"0x{r.start:08X}", f"0x{r.end:08X}", r.segment, r.module, join(r.libraries),
            join(r.versions), join(r.publics), r.status, join(r.alternatives)]  # fmt: skip


def format_runtime_csv(report: LibMatchReport, name: str) -> str:
    """The runtime.csv text: the generated-by comment, the header, one row per range."""
    buf = io.StringIO()
    buf.write(RUNTIME_CSV_COMMENT.format(name=name) + "\n")
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(RUNTIME_CSV_COLUMNS)
    writer.writerows(_cells(r) for r in sorted(report.ranges, key=_range_order))
    return buf.getvalue()


def write_runtime_csv(path: Path, report: LibMatchReport, name: str) -> None:
    """Write format_runtime_csv atomically, creating the parent directories."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    _write_atomic(path, format_runtime_csv(report, name).encode("utf-8"))


def _split(cell: str) -> tuple[str, ...]:
    return tuple(cell.split(_LIST_SEPARATOR)) if cell else ()


def _parse_row(row: dict[str, str]) -> MatchRange:
    return MatchRange(
        start=int(row["start"], 16),
        end=int(row["end"], 16),
        segment=row["segment"],
        module=row["module"],
        libraries=_split(row["libraries"]),
        versions=_split(row["versions"]),
        publics=_split(row["publics"]),
        status=row["status"],
        alternatives=_split(row["alternatives"]),
    )


def read_runtime_csv(path: Path) -> list[MatchRange]:
    """The rows of a runtime.csv; comment lines (starting with #) are skipped."""
    lines = [line for line in Path(path).read_text(encoding="utf-8").splitlines()
             if not line.startswith("#")]  # fmt: skip
    reader = csv.DictReader(lines)
    if tuple(reader.fieldnames or ()) != RUNTIME_CSV_COLUMNS:
        raise LibMatchError(f"{path}: header is not {','.join(RUNTIME_CSV_COLUMNS)}")
    rows = []
    for number, row in enumerate(reader, start=1):
        try:
            rows.append(_parse_row(row))
        except (TypeError, ValueError) as exc:
            raise LibMatchError(f"{path}: data row {number}: {exc}") from exc
    return rows


def runtime_csv_path(name: str) -> Path:
    """config/<stem>/runtime.csv for a manifest name (D-16)."""
    return config_dir(name) / "runtime.csv"
