@dataclass(frozen=True)
class LoadedLibrary:
    version: str
    relpath: str  # POSIX path relative to LIB386, e.g. "DOS/CLIB3R.LIB"
    library: Library


@dataclass(frozen=True)
class Skipped:
    """A library, module or segment that was not matched, and why."""

    version: str
    library: str
    module: str
    segment: str
    reason: str


@dataclass(frozen=True)
class Candidate:
    """One verified placement of one library's segment."""

    start: int
    end: int
    segment: str
    module: str
    library: str
    version: str
    publics: tuple[str, ...]


@dataclass(frozen=True)
class MatchRange:
    """One runtime.csv row: [start, end) in linear addresses."""

    start: int
    end: int
    segment: str
    module: str
    libraries: tuple[str, ...]
    versions: tuple[str, ...]
    publics: tuple[str, ...]
    status: str
    alternatives: tuple[str, ...] = ()

    def to_json(self) -> dict[str, Any]:
        return {k: list(v) if isinstance(v, tuple) else v for k, v in asdict(self).items()}

    def describe(self) -> str:
        return f"{self.start:#010x}..{self.end:#010x} ({self.module})"


@dataclass(frozen=True)
class TargetView:
    """The EXE side: its code object (unrelocated) and every byte an LE fixup writes."""

    code: bytes
    base: int
    fixup_bytes: frozenset[int]
    image: bytes = b""  # the whole flat image, indexed by linear address
    fixup_targets: Mapping[int, int] = field(default_factory=dict)  # LE fixup site -> target


def _counts(items: Iterable[str]) -> str:
    tally: dict[str, int] = defaultdict(int)
    for item in items:
        tally[item] += 1
    return ", ".join(f"{name} {n}" for name, n in sorted(tally.items())) or "none"


@dataclass(frozen=True)
class LibMatchReport:
    exe: str
    code_base: int
    code_size: int
    ranges: tuple[MatchRange, ...]
    skipped: tuple[Skipped, ...]
    dropped: tuple[MatchRange, ...] = ()
    resolved: tuple[tuple[str, int], ...] = ()  # (rule, groups it narrowed to one module)

    @property
    def covered(self) -> int:
        return sum(r.end - r.start for r in self.ranges)

    def format(self) -> str:
        """One line per range, then a summary line; dropped ranges are listed after it."""
        lines = [
            f"0x{r.start:08X}-0x{r.end:08X}  {r.module}  {_LIST_SEPARATOR.join(r.libraries)}  "
            f"{_LIST_SEPARATOR.join(r.versions)}  {r.status}"
            for r in self.ranges
        ]
        lines.append(
            f"{self.exe}: {len(self.ranges)} ranges, {self.covered} of {self.code_size} code "
            f"bytes; skipped: {_counts(_reason_kind(s.reason) for s in self.skipped)}; "
            f"dropped {len(self.dropped)}; resolved: "
            f"{', '.join(f'{rule} {n}' for rule, n in self.resolved) or 'none'}; ambiguous "
            f"{sum(r.status == STATUS_AMBIGUOUS for r in self.ranges)}"
        )
        lines += [f"dropped {r.describe()}" for r in self.dropped]
        return "\n".join(lines)

    def to_json(self) -> dict[str, Any]:
        return {
            "exe": self.exe,
            "code_base": self.code_base,
            "code_size": self.code_size,
            "ranges": [r.to_json() for r in self.ranges],
            "skipped": [asdict(s) for s in self.skipped],
            "dropped": [r.to_json() for r in self.dropped],
            "resolved": dict(self.resolved),
        }


def _reason_kind(reason: str) -> str:
    """The reason without its detail: "parse error at 0x10: ..." counts as "parse error"."""
    return "parse error" if reason.startswith("parse error") else reason


# ---- loading the libraries ----


def _library_order(relpath: str) -> tuple[int, str]:
    """Root and DOS/ libraries first, then the rest, each group in POSIX path order."""
    parts = PurePosixPath(relpath).parts
    first = len(parts) == 1 or parts[0].upper() == _FIRST_DIR
    return (0 if first else 1, relpath)


def iter_library_paths(tree: Path) -> list[Path]:
    """Every *.LIB (suffix compared case-insensitively) under tree/LIB386, root and DOS/ first."""
    lib_dir = Path(tree) / LIB_DIR
    if not lib_dir.is_dir():
        return []
    paths = [p for p in lib_dir.rglob("*") if p.is_file() and p.suffix.upper() == _LIB_SUFFIX]
    return sorted(paths, key=lambda p: _library_order(p.relative_to(lib_dir).as_posix()))


def _load_one(version: str, relpath: str, path: Path) -> tuple[LoadedLibrary | None, list[Skipped]]:
    data = path.read_bytes()
    if not is_omf_library(data):
        return None, [Skipped(version, relpath, "", "", "not OMF")]
    try:
        library = read_library(data, path=relpath)
    except OMFError as exc:
        return None, [Skipped(version, relpath, "", "", f"parse error: {exc}")]
    skips = [
        Skipped(version, relpath, "", "", f"parse error at {f.offset:#x}: {f.message}")
        for f in library.failures
    ]
    return LoadedLibrary(version, relpath, library), skips


def load_libraries(
    watcom_dir: Path, versions: Sequence[str] = SWEPT_VERSIONS
) -> tuple[list[LoadedLibrary], list[Skipped]]:
    """Every OMF library of every version's LIB386 tree; the rest are recorded as Skipped."""
    loaded: list[LoadedLibrary] = []
    skipped: list[Skipped] = []
    for version in versions:
        tree = Path(watcom_dir) / version
        if not (tree / LIB_DIR).is_dir():
            skipped.append(Skipped(version, LIB_DIR, "", "", f"no {LIB_DIR} directory"))
            continue
        for path in iter_library_paths(tree):
            relpath = path.relative_to(tree / LIB_DIR).as_posix()
            library, skips = _load_one(version, relpath, path)
            skipped += skips
            if library is not None:
                loaded.append(library)
    return loaded, skipped


# ---- the EXE side ----


def target_view(le: LE) -> TargetView:
    """The first executable object of `le` and the byte set of every LE fixup."""
    obj = next((o for o in le.objects if o.flags & _OBJ_EXECUTABLE), None)
    if obj is None:
        raise LibMatchError("the EXE has no executable object")
    image = bytes(le.load_flat())
    fixups = le.fixups()
    fixup_bytes = frozenset(fx.src_va + k for fx in fixups for k in range(fx.size))
    targets = {fx.src_va: fx.target_va for fx in fixups}
    return TargetView(image[obj.base : obj.end], obj.base, fixup_bytes, image, targets)


def verify_at(
    code: bytes,
    base: int,
    va: int,
    data: bytes,
    mask: frozenset[int],
    absolute: frozenset[int],
    fixup_bytes: frozenset[int],
) -> bool:
    """True when `data` sits at offset `base` of `code` (linear address `va`): every unmasked
    byte equal and free of LE fixups, and an LE fixup at every absolute library fixup site."""
    if base < 0 or base + len(data) > len(code):
        return False
    for k, byte in enumerate(data):
        if k in mask:
            continue
        if code[base + k] != byte or (va + k) in fixup_bytes:
            return False
    return all((va + off) in fixup_bytes for off in absolute)


# ---- scanning ----


@dataclass(frozen=True, eq=False)
class _Owner:
    """One CODE segment of one module of one library."""

    version: str
    library: str
    module: Module
    segment: Segment

    @property
    def module_name(self) -> str:
        # THEADR names may carry a path or an extension; the stem is the module name.
        return PureWindowsPath(self.module.name).stem

    @property
    def publics(self) -> tuple[str, ...]:
        names = {p.name for p in self.module.publics if p.segment_index == self.segment.index}
        return tuple(sorted(names))


@dataclass(frozen=True, eq=False)
class _Hit:
    owner: _Owner
    start: int

    @property
    def end(self) -> int:
        return self.start + self.owner.segment.length

    def candidate(self) -> Candidate:
        o = self.owner
        return Candidate(self.start, self.end, o.segment.name, o.module_name, o.library,
                         o.version, o.publics)  # fmt: skip


def _code_segments(libraries: Iterable[LoadedLibrary]) -> Iterator[_Owner]:
    for lib in libraries:
        for module in lib.library.modules:
            for seg in module.segments:
                if seg.is_code and seg.length > 0:
                    yield _Owner(lib.version, lib.relpath, module, seg)


def _absolute_sites(seg: Segment) -> frozenset[int]:
    return frozenset(f.offset for f in seg.fixups if f.segment_relative)


def _unmasked_runs(length: int, mask: frozenset[int]) -> Iterator[tuple[int, int]]:
    start = None
    for k in range(length):
        if k not in mask:
            start = k if start is None else start
            continue
        if start is not None:
            yield start, k
            start = None
    if start is not None:
        yield start, length


def _unmasked_count(seg: Segment) -> int:
    return seg.length - len(seg.mask)


def _skip_reason(seg: Segment, min_unmasked: int) -> str | None:
    if seg.unmaskable:
        return "unmaskable"
    if _unmasked_count(seg) < min_unmasked:
        return "short"
    return None


def _occurrences(code: bytes, needle: bytes) -> Iterator[int]:
    pos = code.find(needle)
    while pos >= 0:
        yield pos
        pos = code.find(needle, pos + 1)


def _placements(view: TargetView, seg: Segment) -> list[int]:
    """Offsets in the code object where `seg` verifies."""
    mask, absolute = seg.mask, _absolute_sites(seg)
    anchor = max(_unmasked_runs(seg.length, mask), key=lambda run: run[1] - run[0], default=None)
    if anchor is None:
        return []  # nothing unmasked to anchor on (only reachable with min_unmasked 0)
    lo, hi = anchor
    found = []
    for hit in _occurrences(view.code, seg.data[lo:hi]):
        base = hit - lo
        if verify_at(view.code, base, view.base + base, seg.data, mask, absolute,
                     view.fixup_bytes):  # fmt: skip
            found.append(base)
    return found


def _sorted_set(items: Iterable[str]) -> tuple[str, ...]:
    return tuple(sorted(set(items)))


def _version_order(version: str) -> tuple[int, str]:
    """Manifest order (SWEPT_VERSIONS), then any other version by name."""
    if version in SWEPT_VERSIONS:
        return (SWEPT_VERSIONS.index(version), "")
    return (len(SWEPT_VERSIONS), version)


def _libraries(hits: Iterable[_Hit]) -> tuple[str, ...]:
    return tuple(sorted({h.owner.library for h in hits}, key=_library_order))


def _versions(hits: Iterable[_Hit]) -> tuple[str, ...]:
    return tuple(sorted({h.owner.version for h in hits}, key=_version_order))


# ---- disambiguation of identical bodies (rules a-d) ----


def _library_family(relpath: str) -> int:
    """0 for a C runtime library, 2 for a C++ one, 1 for anything else (by file name)."""
    name = PurePosixPath(relpath).name.upper()
    if name.startswith(C_LIBRARY_PREFIXES):
        return 0
    if name.startswith(CPP_LIBRARY_PREFIXES):
        return 2
    return 1


def _family(hits: Iterable[_Hit]) -> int:
    return min(_library_family(h.owner.library) for h in hits)


def _by_module(hits: Iterable[_Hit]) -> dict[str, list[_Hit]]:
    by_name: dict[str, list[_Hit]] = defaultdict(list)
    for hit in hits:
        by_name[hit.owner.module_name].append(hit)
    return dict(by_name)


def _data_target(module: Module, fixup: OMFFixup) -> Segment | None:
    """The segment of `module` with initialized bytes that a segment-relative 32-bit fixup
    targets, or None when the fixup gives no data evidence."""
    if not fixup.segment_relative or fixup.size != _FIELD32 or fixup.target_kind != "segment":
        return None
    if not 1 <= fixup.target_index <= len(module.segments):
        return None
    target = module.segments[fixup.target_index - 1]
    if target.length == 0 or target.unmaskable or target.class_name.upper() in _NO_DATA_CLASSES:
        return None
    return target


def _segment_at(image: bytes, va: int, seg: Segment) -> bool:
    """`seg`'s bytes, masked at its own fixups, sit at linear address `va` of the image."""
    if va + seg.length > len(image):
        return False
    mask, window = seg.mask, image[va : va + seg.length]
    return all(k in mask or window[k] == byte for k, byte in enumerate(seg.data))


def _data_consistent(hit: _Hit, view: TargetView, _publics: Mapping[int, frozenset[str]]) -> bool:
    """Rule (a): every data segment the code addresses holds its bytes where the LE fixup at
    that site points (segment VA = LE target - OMF displacement - addend stored at the site)."""
    seg = hit.owner.segment
    for fixup in seg.fixups:
        target = _data_target(hit.owner.module, fixup)
        if target is None:
            continue
        target_va = view.fixup_targets.get(hit.start + fixup.offset)
        if target_va is None:
            return False
        addend = int.from_bytes(seg.data[fixup.offset : fixup.offset + _FIELD32], "little")
        seg_va = (target_va - fixup.displacement - addend) & 0xFFFFFFFF
        if not _segment_at(view.image, seg_va, target):
            return False
    return True


def _calls_consistent(hit: _Hit, view: TargetView, publics: Mapping[int, frozenset[str]]) -> bool:
    """Rule (b): no rel32 call or jump to an extern lands on the start of a matched range
    whose publics do not include that extern's name."""
    for fixup in hit.owner.segment.fixups:
        if fixup.segment_relative or fixup.size != _FIELD32 or fixup.target_kind != "extern":
            continue
        site = hit.start + fixup.offset
        rel = int.from_bytes(view.image[site : site + _FIELD32], "little", signed=True)
        names = publics.get((site + _FIELD32 + rel) & 0xFFFFFFFF)
        if names is not None and fixup.target_name not in names:
            return False
    return True


def _narrow(
    by_name: dict[str, list[_Hit]], passes: Callable[[_Hit], bool]
) -> dict[str, list[_Hit]]:
    """The modules with a hit that passes; all of them when none passes (evidence never
    empties a group)."""
    passing = {name: hits for name, hits in by_name.items() if any(passes(h) for h in hits)}
    return passing or by_name


def _c_before_cpp(by_name: dict[str, list[_Hit]]) -> dict[str, list[_Hit]]:
    """Rule (c): with candidates from both C and C++ runtime libraries, drop the C++ ones."""
    families = {name: _family(hits) for name, hits in by_name.items()}
    if 0 not in families.values() or 2 not in families.values():
        return by_name
    return {name: hits for name, hits in by_name.items() if families[name] != 2}


def _disambiguate(
    hits: list[_Hit], view: TargetView, publics: Mapping[int, frozenset[str]]
) -> tuple[list[_Hit], str | None]:
    """The hits left after rules (a)-(c), applied in order to a group with more than one
    module name, and the rule that left a single module (None when none did)."""
    by_name = _by_module(hits)
    if len(by_name) < 2:
        return hits, None
    steps: list[tuple[str, Callable[[dict[str, list[_Hit]]], dict[str, list[_Hit]]]]] = [
        (RULE_DATA, lambda b: _narrow(b, lambda h: _data_consistent(h, view, publics))),
        (RULE_CALLS, lambda b: _narrow(b, lambda h: _calls_consistent(h, view, publics))),
        (RULE_C_BEFORE_CPP, _c_before_cpp),
    ]
    for rule, step in steps:
        by_name = step(by_name)
        if len(by_name) == 1:
            return [h for group in by_name.values() for h in group], rule
    return [h for group in by_name.values() for h in group], None


def _range_publics(groups: Mapping[tuple[int, int], list[_Hit]]) -> dict[int, frozenset[str]]:
    """Range start -> every public of every candidate placed there (for rule b)."""
    publics: dict[int, set[str]] = defaultdict(set)
    for (start, _end), hits in groups.items():
        publics[start].update(p for h in hits for p in h.owner.publics)
    return {start: frozenset(names) for start, names in publics.items()}


def _row(start: int, end: int, hits: list[_Hit]) -> MatchRange:
    """One range from every hit at [start, end): unique when they share one module name. The
    libraries, versions and publics are those of every hit (D-07: every version whose bytes
    match), so a module renamed between versions still shows all of them."""
    by_name = _by_module(hits)
    # Rule (d): still tied -> ambiguous; the module shown is the first by (C before C++, name).
    names = sorted(by_name, key=lambda name: (_family(by_name[name]), name))
    chosen = by_name[names[0]]
    others = [h for h in hits if h.owner.module_name != names[0]]
    return MatchRange(
        start=start,
        end=end,
        segment=min(h.owner.segment.name for h in chosen),
        module=names[0],
        libraries=_libraries(hits),
        versions=_versions(hits),
        publics=_sorted_set(p for h in hits for p in h.owner.publics),
        status=STATUS_UNIQUE if not others else STATUS_AMBIGUOUS,
        alternatives=_sorted_set(f"{h.owner.module_name}@{h.owner.library}" for h in others),
    )


def _overlap_error(outer: MatchRange, inner: MatchRange) -> LibMatchError:
    return LibMatchError(
        f"ranges 0x{outer.start:08x}..0x{outer.end:08x} ({outer.module}) and "
        f"0x{inner.start:08x}..0x{inner.end:08x} ({inner.module}) overlap without one "
        "containing the other"
    )


def _drop_contained(
    ranges: Iterable[MatchRange],
) -> tuple[tuple[MatchRange, ...], tuple[MatchRange, ...]]:
    """(kept, dropped): a range strictly inside a longer one is dropped; a partial overlap
    raises LibMatchError naming both. Touching ranges (one's end is the next's start) stay."""
    kept: list[MatchRange] = []
    dropped: list[MatchRange] = []
    for r in sorted(ranges, key=lambda r: (r.start, -r.end)):
        outer = kept[-1] if kept else None
        if outer is None or r.start >= outer.end:
            kept.append(r)
        elif r.end <= outer.end:
            dropped.append(r)
        else:
            raise _overlap_error(outer, r)
    return tuple(kept), tuple(sorted(dropped, key=_range_order))


def _range_order(r: MatchRange) -> tuple[int, int]:
    return (r.start, r.end)


def scan_exe(
    le: LE,
    libraries: Sequence[LoadedLibrary],
    *,
    exe: str = "",
    min_unmasked: int = MIN_UNMASKED,
    skipped: Sequence[Skipped] = (),
) -> LibMatchReport:
    """Place every CODE segment of `libraries` in the code object of `le`. `skipped` (from
    load_libraries) is carried into the report; segments too short to place or with an
    unknown mask are added to it, never dropped silently."""
    view = target_view(le)
    skips = list(skipped)
    placements: dict[tuple[bytes, frozenset[int], frozenset[int]], list[int]] = {}
    groups: dict[tuple[int, int], list[_Hit]] = defaultdict(list)
    for owner in _code_segments(libraries):
        seg = owner.segment
        reason = _skip_reason(seg, min_unmasked)
        if reason is not None:
            skips.append(Skipped(owner.version, owner.library, owner.module_name, seg.name,
                                 reason))  # fmt: skip
            continue
        # Identical segments (CLIB3R/CLIB3S, several versions) are searched once.
        key = (seg.data, seg.mask, _absolute_sites(seg))
        if key not in placements:
            placements[key] = _placements(view, seg)
        for base in placements[key]:
            hit = _Hit(owner, view.base + base)
            groups[(hit.start, hit.end)].append(hit)
    publics = _range_publics(groups)
    rows: list[MatchRange] = []
    resolved: dict[str, int] = dict.fromkeys(DISAMBIGUATION_RULES, 0)
    for (start, end), hits in groups.items():
        kept, rule = _disambiguate(hits, view, publics)
        if rule is not None:
            resolved[rule] += 1
        rows.append(_row(start, end, kept))
    ranges, dropped = _drop_contained(rows)
    return LibMatchReport(exe, view.base, len(view.code), ranges, tuple(skips), dropped,
                          tuple(resolved.items()))  # fmt: skip


