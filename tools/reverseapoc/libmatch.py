"""Masked library matcher: places Watcom runtime library modules in an EXE's code object.

Each CODE segment of each OMF library module under `<watcom>/<version>/LIB386/` is matched as a
whole against the code object of the EXE (D-04, D-05). Both sides are masked: the bytes the
library's own fixups (and backpatches) write are not compared, and neither are the bytes of the
EXE's LE fixups. A candidate passes when every unmasked byte is equal, no LE fixup covers an
unmasked library byte, and an LE fixup sits at every segment-relative (absolute) library fixup
site. Self-relative sites (rel32 calls and jumps) were resolved by wlink and carry no LE fixup.

There is no function list before Phase 5, so the search slides over the whole code object: the
segment's longest run of unmasked bytes is the anchor, every occurrence of it is a candidate, and
each candidate is verified in full. Matches at the same range merge into one row whose libraries
and versions are the sets of every library and version that matched there (D-07).

The masking idea comes from KKND-Decomp's lib_match.py; its search over known function starts
and 48-byte prefixes is replaced by the whole-segment slide above. Output (runtime.csv, reports,
JSON) holds addresses, counts, segment, module, library and public names only, never bytes.
"""

